import assert from 'node:assert';
import { describe, test } from 'node:test';
import {
	buildMigrationPlan,
	droppedColumn,
	foreignKeysOf,
	formatMigrationPlan,
	primaryKeyColumns,
	replaceOutsideLiterals,
} from './migrations/plan.js';

const plan = (sql: string, target: 'distributed' = 'distributed') => buildMigrationPlan({ '001.sql': sql }, target);
const steps = (sql: string) => plan(sql).files[0].steps;

describe('migration rewriter (distributed)', () => {
	test('DDL runs outside the transaction, DML inside', () => {
		const s = steps(
			"CREATE TABLE t (id TEXT PRIMARY KEY);\nINSERT INTO t VALUES ('a');\nINSERT INTO t VALUES ('b');",
		);
		assert.deepStrictEqual(
			s.map((x) => x.transactional),
			[false, true, true],
		);
	});

	test('SERIAL, BIGSERIAL and SMALLSERIAL all become BIGINT identity columns with CACHE 65536', () => {
		const [s] = steps(
			"CREATE TABLE t (id SERIAL PRIMARY KEY, b BIGSERIAL, c SMALLSERIAL, note TEXT DEFAULT 'serial');",
		);
		assert.strictEqual(
			s.sql,
			'CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY, ' +
				'b BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536), c BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536), ' +
				"note TEXT DEFAULT 'serial')",
		);
		assert.match(s.note ?? '', /SERIAL rewritten to BIGINT/);
	});

	test('an identity column on a smaller type becomes BIGINT, and gets CACHE 65536 when it has none', () => {
		const [a] = steps('CREATE TABLE t (id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY);');
		assert.match(a.sql, /id BIGINT GENERATED ALWAYS AS IDENTITY \(CACHE 65536\) PRIMARY KEY/);
		const [b] = steps('CREATE TABLE t (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY);');
		assert.match(b.sql, /id BIGINT GENERATED BY DEFAULT AS IDENTITY \(START WITH 10 CACHE 65536\) PRIMARY KEY/);
		const [c] = steps('CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY);');
		assert.match(c.sql, /\(CACHE 1\)/, 'an explicit CACHE 1 is kept');
		assert.strictEqual(c.note, undefined);
		const [d] = steps('ALTER TABLE t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;');
		assert.match(d.sql, /ADD GENERATED BY DEFAULT AS IDENTITY \(CACHE 65536\)/);
	});

	test('CREATE SEQUENCE gets CACHE 65536 and a bigint type; a small explicit cache is rejected', () => {
		const [a] = steps('CREATE SEQUENCE order_no;');
		assert.strictEqual(a.sql, 'CREATE SEQUENCE order_no CACHE 65536');
		const [b] = steps('CREATE SEQUENCE IF NOT EXISTS order_no AS integer START WITH 100;');
		assert.strictEqual(b.sql, 'CREATE SEQUENCE IF NOT EXISTS order_no CACHE 65536 AS BIGINT START WITH 100');
		const [c] = steps('CREATE SEQUENCE order_no CACHE 1;');
		assert.strictEqual(c.sql, 'CREATE SEQUENCE order_no CACHE 1');
		assert.throws(() => plan('CREATE SEQUENCE order_no CACHE 50;'), /CACHE 1 or CACHE >= 65536 \(got 50\)/);
	});

	test('CREATE INDEX becomes ASYNC plus a wait on the job', () => {
		const [create, wait] = steps('CREATE UNIQUE INDEX idx ON t (a);');
		assert.match(create.sql, /CREATE UNIQUE INDEX ASYNC idx ON t \(a\)/);
		assert.strictEqual(create.transactional, false);
		assert.strictEqual(wait.kind, 'wait-job');
		assert.strictEqual(wait.sql, 'SELECT sys.wait_for_job($job)');
	});

	test('ADD CONSTRAINT CHECK gets NOT VALID, an ASYNC validation, and a wait', () => {
		const s = steps('ALTER TABLE t ADD CONSTRAINT c CHECK (a > 0);');
		assert.deepStrictEqual(
			s.map((x) => x.kind),
			['statement', 'validate-constraint', 'wait-job'],
		);
		assert.match(s[0].sql, /CHECK \(a > 0\) NOT VALID$/);
		assert.strictEqual(s[1].sql, 'ALTER TABLE ASYNC t VALIDATE CONSTRAINT c');
		assert.ok(s.every((x) => !x.transactional));
	});

	test('ADD CONSTRAINT FOREIGN KEY gets the same treatment; an inline REFERENCES in CREATE TABLE runs as written', () => {
		const s = steps(
			'ALTER TABLE posts ADD CONSTRAINT posts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;',
		);
		assert.strictEqual(
			s[0].sql,
			'ALTER TABLE posts ADD CONSTRAINT posts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE NOT VALID',
		);
		assert.strictEqual(s[1].sql, 'ALTER TABLE ASYNC posts VALIDATE CONSTRAINT posts_user');
		assert.strictEqual(s[2].kind, 'wait-job');
		const [inline] = steps('CREATE TABLE posts (id TEXT PRIMARY KEY, user_id TEXT REFERENCES users(id));');
		assert.strictEqual(inline.sql, 'CREATE TABLE posts (id TEXT PRIMARY KEY, user_id TEXT REFERENCES users(id))');
		// Already NOT VALID: not doubled.
		const [already] = steps('ALTER TABLE t ADD CONSTRAINT c CHECK (a > 0) NOT VALID;');
		assert.ok(!/NOT VALID NOT VALID/.test(already.sql));
	});

	test('a hand-written ALTER TABLE ASYNC … VALIDATE CONSTRAINT gets a wait of its own', () => {
		const s = steps('ALTER TABLE ASYNC t VALIDATE CONSTRAINT c;');
		assert.deepStrictEqual(
			s.map((x) => x.kind),
			['validate-constraint', 'wait-job'],
		);
	});

	test('dropping a primary-key column is rejected using the CREATE TABLE seen earlier in the plan', () => {
		assert.throws(
			() =>
				buildMigrationPlan(
					{
						'001.sql': 'CREATE TABLE t (id TEXT PRIMARY KEY, a INT);',
						'002.sql': 'ALTER TABLE t DROP COLUMN id;',
					},
					'distributed',
				),
			/002\.sql: DSQL cannot drop primary-key column 'id' of 't'/,
		);
		const ok = buildMigrationPlan(
			{
				'001.sql': 'CREATE TABLE t (a INT, b INT, CONSTRAINT t_pk PRIMARY KEY (a, b), c TEXT);',
				'002.sql': 'ALTER TABLE t DROP COLUMN c;',
			},
			'distributed',
		);
		assert.strictEqual(ok.files[1].steps[0].sql, 'ALTER TABLE t DROP COLUMN c');
		assert.throws(
			() =>
				buildMigrationPlan(
					{
						'001.sql': 'CREATE TABLE t (a INT, b INT, PRIMARY KEY (a, b));',
						'002.sql': 'ALTER TABLE t DROP b;',
					},
					'distributed',
				),
			/primary-key column 'b'/,
		);
	});

	test('rejects unsupported statements with the file and the doc page', () => {
		assert.throws(
			() => buildMigrationPlan({ '002_rls.sql': 'CREATE POLICY p ON t USING (true);' }, 'distributed'),
			(e: Error) =>
				e.name === 'DsqlMigrationValidationError' &&
				/002_rls\.sql: DSQL does not support Row Level Security/.test(e.message) &&
				/docs\.aws\.amazon\.com\/aurora-dsql/.test(e.message),
		);
		assert.throws(() => plan('ALTER TABLE t ALTER COLUMN a SET NOT NULL;'), /SET NOT NULL/);
		assert.throws(() => plan('ALTER TABLE t ADD CHECK (a > 0);'), /Name the constraint/);
	});

	test('golden plan: one file with a table, a foreign key, a check, an index, and a seed', () => {
		const text = formatMigrationPlan(
			buildMigrationPlan(
				{
					'001_orders.sql': [
						'CREATE TABLE orders (id SERIAL PRIMARY KEY, user_id TEXT NOT NULL, total INTEGER NOT NULL);',
						'ALTER TABLE orders ADD CONSTRAINT orders_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT;',
						'ALTER TABLE orders ADD CONSTRAINT orders_total CHECK (total >= 0);',
						'CREATE INDEX orders_user_idx ON orders (user_id);',
						"INSERT INTO orders (user_id, total) VALUES ('u1', 10);",
						"INSERT INTO orders (user_id, total) VALUES ('u2', 20);",
					].join('\n'),
				},
				'distributed',
			),
			{ pending: new Set(['001_orders.sql']) },
		);
		assert.strictEqual(
			text,
			[
				'Migration plan (target: distributed)',
				'',
				'001_orders.sql [pending]',
				'  1. CREATE TABLE orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY, user_id TEXT NOT NULL, total INTEGER NOT NULL)  -- SERIAL rewritten to BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536)',
				'  2. ALTER TABLE orders ADD CONSTRAINT orders_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT NOT VALID  -- FOREIGN KEY constraint added NOT VALID, then validated asynchronously',
				'  3. [validate-constraint] ALTER TABLE ASYNC orders VALIDATE CONSTRAINT orders_user',
				'  4. [wait-job] SELECT sys.wait_for_job($job)  -- waits for the constraint validation job DSQL returned',
				'  5. ALTER TABLE orders ADD CONSTRAINT orders_total CHECK (total >= 0) NOT VALID  -- CHECK constraint added NOT VALID, then validated asynchronously',
				'  6. [validate-constraint] ALTER TABLE ASYNC orders VALIDATE CONSTRAINT orders_total',
				'  7. [wait-job] SELECT sys.wait_for_job($job)  -- waits for the constraint validation job DSQL returned',
				'  8. CREATE INDEX ASYNC orders_user_idx ON orders (user_id)  -- CREATE INDEX rewritten to CREATE INDEX ASYNC',
				'  9. [wait-job] SELECT sys.wait_for_job($job)  -- waits for the index build job DSQL returned',
				'  BEGIN',
				"    10. INSERT INTO orders (user_id, total) VALUES ('u1', 10)",
				"    11. INSERT INTO orders (user_id, total) VALUES ('u2', 20)",
				'  COMMIT',
				'  record 001_orders.sql in _migrations',
				'  foreign keys and their referential actions:',
				'    - REFERENCES users(id) ON DELETE RESTRICT',
			].join('\n'),
		);
	});

	test('lists foreign keys with their referential actions', () => {
		const fks = foreignKeysOf(
			'CREATE TABLE posts (id TEXT, user_id TEXT REFERENCES users(id) MATCH SIMPLE ON DELETE CASCADE, org_id TEXT REFERENCES orgs(id))',
		);
		assert.deepStrictEqual(fks, ['REFERENCES users(id) ON DELETE CASCADE', 'REFERENCES orgs(id) (NO ACTION)']);
	});

	test('helpers', () => {
		assert.deepStrictEqual(
			primaryKeyColumns('CREATE TABLE IF NOT EXISTS "App".Users (id UUID PRIMARY KEY, n INT)'),
			{
				table: 'users',
				columns: ['id'],
			},
		);
		assert.deepStrictEqual(droppedColumn('ALTER TABLE t DROP COLUMN IF EXISTS "Legacy"'), {
			table: 't',
			column: 'Legacy',
		});
		assert.strictEqual(droppedColumn('ALTER TABLE t DROP CONSTRAINT c'), undefined);
		assert.strictEqual(replaceOutsideLiterals("SELECT 'a b' AS x, a b", /\ba\b/g, 'Z'), "SELECT 'a b' AS x, Z b");
	});
});
