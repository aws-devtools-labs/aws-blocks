import assert from 'node:assert';
import { describe, test } from 'node:test';
import { isBlocksError } from '@aws-blocks/core';
import { DSQL_MIGRATION_VALIDATION_ERROR_NAME } from '../errors.js';
import { buildMigrationPlan, lintMigrationFiles } from './plan.js';

const steps = (sql: string) => buildMigrationPlan({ '001.sql': sql }).files[0].steps;

describe('migration plan (dsql): sequencing', () => {
	test('DDL runs outside the transaction, DML inside', () => {
		const s = steps(
			"CREATE TABLE t (id TEXT PRIMARY KEY);\nINSERT INTO t VALUES ('a');\nINSERT INTO t VALUES ('b');",
		);
		assert.deepStrictEqual(
			s.map((x) => x.transactional),
			[false, true, true],
		);
		assert.ok(s.every((x) => x.kind === 'statement'));
	});

	test('CREATE INDEX ASYNC and CREATE UNIQUE INDEX ASYNC are followed by a wait on the job DSQL returns', () => {
		const [create, wait] = steps('CREATE INDEX ASYNC t_n ON t (n);');
		assert.deepStrictEqual(create, {
			kind: 'statement',
			sql: 'CREATE INDEX ASYNC t_n ON t (n)',
			transactional: false,
		});
		assert.strictEqual(wait.kind, 'wait-job');
		assert.strictEqual(wait.transactional, false);
		const [unique, uniqueWait] = steps('CREATE UNIQUE INDEX ASYNC IF NOT EXISTS u ON t (a) INCLUDE (b);');
		assert.strictEqual(unique.sql, 'CREATE UNIQUE INDEX ASYNC IF NOT EXISTS u ON t (a) INCLUDE (b)');
		assert.strictEqual(uniqueWait.kind, 'wait-job');
	});

	test('ALTER TABLE ASYNC … VALIDATE CONSTRAINT is followed by a wait on the job DSQL returns', () => {
		const s = steps('ALTER TABLE ASYNC t VALIDATE CONSTRAINT c;');
		assert.deepStrictEqual(
			s.map((x) => x.kind),
			['statement', 'wait-job'],
		);
		assert.strictEqual(s[0].sql, 'ALTER TABLE ASYNC t VALIDATE CONSTRAINT c');
		assert.ok(s.every((x) => !x.transactional));
	});

	test('a constraint added NOT VALID is one statement; nothing is synthesized after it', () => {
		const s = steps(
			'ALTER TABLE posts ADD CONSTRAINT posts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE NOT VALID;',
		);
		assert.deepStrictEqual(s, [
			{
				kind: 'statement',
				sql: 'ALTER TABLE posts ADD CONSTRAINT posts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE NOT VALID',
				transactional: false,
			},
		]);
	});

	test('the SQL of every step is the file’s statement, unchanged', () => {
		const file = [
			'CREATE TABLE orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), total INTEGER NOT NULL);',
			'CREATE TABLE invoices (id BIGINT GENERATED ALWAYS AS IDENTITY (CACHE 1) PRIMARY KEY);',
			'CREATE SEQUENCE order_no AS BIGINT START WITH 100 CACHE 65536;',
			'ALTER TABLE orders ADD CONSTRAINT orders_total CHECK (total >= 0) NOT VALID;',
			'ALTER TABLE ASYNC orders VALIDATE CONSTRAINT orders_total;',
			'CREATE INDEX ASYNC orders_user_idx ON orders (user_id);',
			"INSERT INTO orders (user_id, total) VALUES ('u1', 10);",
			"INSERT INTO orders (user_id, total) VALUES ('u2', 20);",
		];
		const s = steps(file.join('\n'));
		assert.deepStrictEqual(
			s.filter((x) => x.kind !== 'wait-job').map((x) => x.sql),
			file.map((x) => x.replace(/;$/, '')),
		);
		assert.deepStrictEqual(
			s.map((x) => x.kind),
			[
				'statement',
				'statement',
				'statement',
				'statement',
				'statement',
				'wait-job',
				'statement',
				'wait-job',
				'statement',
				'statement',
			],
		);
		assert.deepStrictEqual(
			s.map((x) => x.transactional),
			[false, false, false, false, false, false, false, false, true, true],
		);
	});

	test('comments and string literals do not produce steps or findings', () => {
		const s = steps(
			"-- CREATE INDEX later\nCREATE TABLE t (id TEXT PRIMARY KEY, note TEXT);\n/* TRUNCATE t; */\nINSERT INTO t VALUES ('a', 'CREATE INDEX t_n ON t (n); SERIAL');",
		);
		assert.strictEqual(s.length, 2);
		assert.match(s[1].sql, /CREATE INDEX t_n ON t \(n\); SERIAL/);
	});

	test('files are planned in name order', () => {
		const p = buildMigrationPlan({
			'002_seed.sql': "INSERT INTO t VALUES ('a');",
			'001_init.sql': 'CREATE TABLE t (id TEXT PRIMARY KEY);',
		});
		assert.deepStrictEqual(
			p.files.map((f) => f.file),
			['001_init.sql', '002_seed.sql'],
		);
	});
});

describe('migration lint (dsql): what stops it', () => {
	// Which statements dsql-lint rejects, and with which rule, is dsql/validation.test.ts's; here it is the
	// error one deploy attempt shows.
	test('every finding across every file is listed, with its file, rule and doc page', () => {
		assert.throws(
			() =>
				lintMigrationFiles({
					'001.sql': 'CREATE TABLE t (id SERIAL PRIMARY KEY);\nCREATE INDEX t_id ON t (id);',
					'002.sql': 'TRUNCATE t;',
				}),
			(e: unknown) => {
				assert.ok(isBlocksError(e, DSQL_MIGRATION_VALIDATION_ERROR_NAME));
				const lines = e.message.split('\n').slice(1);
				assert.strictEqual(lines.length, 3, e.message);
				assert.match(lines[0], /^ {2}001\.sql: serial_type: /);
				assert.match(lines[1], /^ {2}001\.sql: index_async: /);
				assert.match(lines[2], /^ {2}002\.sql: truncate: /);
				for (const line of lines) assert.match(line, /docs\.aws\.amazon\.com\/aurora-dsql/);
				return true;
			},
		);
	});

	test('a clean file lints without error; the plan itself never lints', () => {
		lintMigrationFiles({ '001.sql': 'CREATE TABLE t (id TEXT PRIMARY KEY);' });
		// The migration Lambda plans files checked at synth, without the linter.
		const p = buildMigrationPlan({ '001.sql': 'CREATE TABLE t (id SERIAL PRIMARY KEY);' });
		assert.strictEqual(p.files[0].steps[0].sql, 'CREATE TABLE t (id SERIAL PRIMARY KEY)');
	});
});
