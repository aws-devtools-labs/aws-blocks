describe('dsql-lint integration', () => {
	test('the binary for this platform is installed', () => {
		assert.ok(isDsqlLintAvailable(), 'install @aws/dsql-lint with optional dependencies');
		assert.match(dsqlLintBinary(), /dsql-lint(\.exe)?$/);
	});

	for (const [sql, rule] of REJECTED) {
		test(`rejects ${rule}: ${sql.slice(0, 60)}`, () => {
			const issues = findStatementIssues(sql);
			assert.ok(
				issues.some((i) => i.rule === rule),
				`expected rule '${rule}', got ${JSON.stringify(issues.map((i) => i.rule))}`,
			);
			assert.throws(
				() => validateStatement(sql),
				(e: Error) =>
					e.name === 'DsqlValidationError' && e.message.includes(rule) && /aurora-dsql/.test(e.message),
			);
		});
	}

	test('accepts what DSQL runs today', () => {
		for (const sql of ACCEPTED) assert.deepStrictEqual(findStatementIssues(sql), [], sql);
	});

	test('a file of statements is linted as one text, each finding carrying its line', () => {
		const diagnostics = lintSql('CREATE TABLE t (id TEXT PRIMARY KEY);\nTRUNCATE t;\nSELECT 1;');
		assert.strictEqual(diagnostics.length, 1);
		assert.strictEqual(diagnostics[0].rule, 'truncate');
		assert.strictEqual(diagnostics[0].line, 2);
	});

	test('results are cached per text', () => {
		const first = lintSql('SELECT 42');
		assert.strictEqual(lintSql('SELECT 42'), first);
	});
});

describe('TransactionTracker', () => {
	test('one DDL per transaction, never with DML', () => {
		const t = new TransactionTracker();
		t.recordStatement('CREATE TABLE a (id INT)');
		assert.throws(() => t.recordStatement('CREATE TABLE b (id INT)'), /only 1 DDL statement/);
		const u = new TransactionTracker();
		u.recordStatement('INSERT INTO a VALUES (1)');
		assert.throws(() => u.recordStatement('CREATE TABLE b (id INT)'), /DDL and DML in the same transaction/);
	});

	test('3,000 rows and 10 MiB per transaction, reported as TransactionRowLimitExceeded', () => {
		const t = new TransactionTracker();
		t.recordRowCount(3000);
		assert.throws(
			() => t.recordRowCount(1),
			(e: Error) => e.name === 'TransactionRowLimitExceededException' && /3001/.test(e.message),
		);
		const u = new TransactionTracker();
		assert.throws(
			() => u.recordStatement('INSERT INTO t (blob) VALUES ($1)', ['x'.repeat(11 * 1024 * 1024)]),
			(e: Error) => e.name === 'TransactionRowLimitExceededException' && /10 MiB/.test(e.message),
		);
	});
});
