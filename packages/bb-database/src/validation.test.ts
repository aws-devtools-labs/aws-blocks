/**
 * The DSQL rule table is its own fixture: every rule's `rejects` examples must
 * trip exactly that rule, and its `accepts` examples must trip no error rule.
 * Re-baselining the validator against a new DSQL release is then a diff of
 * `RULES`, with this test as the check.
 */
import assert from 'node:assert';
import { describe, test } from 'node:test';
import {
	findStatementIssues,
	RULES,
	stripLiteralsAndComments,
	TransactionTracker,
	validateStatement,
} from './validation.js';

describe('DSQL rule table', () => {
	for (const rule of RULES) {
		test(`${rule.severity}: ${rule.message.slice(0, 70)}`, () => {
			assert.ok(rule.rejects.length > 0 && rule.accepts.length > 0, 'every rule carries both kinds of example');
			assert.match(
				rule.doc,
				/^https:\/\/docs\.aws\.amazon\.com\/aurora-dsql\//,
				'every rule cites a DSQL doc page',
			);
			for (const sql of rule.rejects) {
				assert.ok(rule.pattern.test(stripLiteralsAndComments(sql)), `should flag: ${sql}`);
				if (rule.severity === 'error') {
					const issues = findStatementIssues(sql);
					assert.ok(
						issues.some((i) => i.message === rule.message),
						`findStatementIssues should report this rule for: ${sql}`,
					);
				}
			}
			for (const sql of rule.accepts) {
				assert.ok(!rule.pattern.test(stripLiteralsAndComments(sql)), `should not flag: ${sql}`);
				assert.deepStrictEqual(findStatementIssues(sql), [], `no error rule should flag: ${sql}`);
			}
		});
	}

	test('features DSQL added since the 2025 rule set pass', () => {
		for (const sql of [
			'CREATE TABLE posts (id UUID PRIMARY KEY, user_id UUID REFERENCES users(id) ON DELETE CASCADE)',
			'ALTER TABLE posts ADD CONSTRAINT posts_user FOREIGN KEY (user_id) REFERENCES users(id) NOT VALID',
			'ALTER TABLE ASYNC posts VALIDATE CONSTRAINT posts_user',
			'CREATE VIEW active_users AS SELECT * FROM users WHERE active',
			'CREATE SEQUENCE order_no CACHE 65536',
			'CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY)',
			'CREATE TABLE t (id TEXT PRIMARY KEY, doc JSONB)',
			'ALTER TABLE t DROP COLUMN legacy',
			'ALTER DEFAULT PRIVILEGES IN SCHEMA app GRANT SELECT ON TABLES TO reader',
			'CREATE INDEX ASYNC t_lower ON t (lower(name)) WHERE active',
		]) {
			assert.deepStrictEqual(findStatementIssues(sql), [], sql);
		}
	});

	test('literals and comments never trigger a rule', () => {
		assert.deepStrictEqual(
			findStatementIssues("INSERT INTO t (note) VALUES ('TRUNCATE me -- CREATE TRIGGER')"),
			[],
		);
		assert.deepStrictEqual(findStatementIssues('SELECT 1 -- TRUNCATE t'), []);
	});

	test('validateStatement throws a branded DsqlValidationError citing the doc page', () => {
		assert.throws(
			() => validateStatement('TRUNCATE t'),
			(e: Error) => e.name === 'DsqlValidationError' && /aurora-dsql/.test(e.message),
		);
	});
});

describe('TransactionTracker', () => {
	test('one DDL per transaction, never with DML', () => {
		const t = new TransactionTracker();
		t.recordStatement('CREATE TABLE a (id INT)');
		assert.throws(() => t.recordStatement('CREATE TABLE b (id INT)'), /only 1 DDL statement/);
		const u = new TransactionTracker();
		u.recordStatement('INSERT INTO a VALUES (1)');
		assert.throws(() => u.recordStatement('CREATE TABLE b (id INT)'), /DDL and DML in the same transaction/);
	});

	test('3,000 rows and 10 MiB per transaction, reported as TransactionRowLimitExceeded', () => {
		const t = new TransactionTracker();
		t.recordRowCount(3000);
		assert.throws(
			() => t.recordRowCount(1),
			(e: Error) => e.name === 'TransactionRowLimitExceededException' && /3001/.test(e.message),
		);
		const u = new TransactionTracker();
		assert.throws(
			() => u.recordStatement('INSERT INTO t (blob) VALUES ($1)', ['x'.repeat(11 * 1024 * 1024)]),
			(e: Error) => e.name === 'TransactionRowLimitExceededException' && /10 MiB/.test(e.message),
		);
	});
});
