import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import type { DatabaseEngine } from '../common/engine.js';
import { LEDGER_TABLE_NAMES } from '../constants.js';

interface ColumnRow {
	table_name: string;
	column_name: string;
	udt_name: string;
	is_nullable: 'YES' | 'NO';
	column_default: string | null;
	is_identity: 'YES' | 'NO';
	identity_generation: string | null;
	is_generated: string;
}

// What the block's engines return for each PostgreSQL type (README, "Kysely"): `bigint` is a number, `numeric`
// stays a string, the timestamp types are a `Date`. Anything not listed is `unknown`: a wrong guess would type-check.
const SCALARS: Record<string, string> = {
	int2: 'number',
	int4: 'number',
	int8: 'number',
	float4: 'number',
	float8: 'number',
	oid: 'number',
	numeric: 'string',
	money: 'string',
	text: 'string',
	varchar: 'string',
	bpchar: 'string',
	char: 'string',
	name: 'string',
	citext: 'string',
	uuid: 'string',
	bool: 'boolean',
	date: 'Date',
	timestamp: 'Date',
	timestamptz: 'Date',
	time: 'string',
	timetz: 'string',
	interval: 'string',
	json: 'unknown',
	jsonb: 'unknown',
	bytea: 'Uint8Array',
};

function tsType(udt: string): string {
	if (udt.startsWith('_')) {
		const element = SCALARS[udt.slice(1)] ?? 'unknown';
		return element.includes(' ') ? `(${element})[]` : `${element}[]`;
	}
	return SCALARS[udt] ?? 'unknown';
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (name: string): string => (IDENTIFIER.test(name) ? name : JSON.stringify(name));

function columnType(column: ColumnRow): string {
	const base = tsType(column.udt_name) + (column.is_nullable === 'YES' ? ' | null' : '');
	if (column.is_generated === 'ALWAYS' || (column.is_identity === 'YES' && column.identity_generation === 'ALWAYS')) {
		return `GeneratedAlways<${base}>`;
	}
	if (column.column_default !== null || column.is_identity === 'YES') return `Generated<${base}>`;
	return base;
}

export interface TypesFile {
	text: string;
	tables: string[];
}

/** One `Tables` interface for Kysely, from the columns the database reports for `schemaName`. */
export async function generateTypes(engine: DatabaseEngine, schemaName: string): Promise<TypesFile> {
	const rows = await engine.query<ColumnRow>(
		`SELECT c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default, c.is_identity,
		        c.identity_generation, c.is_generated
		   FROM information_schema.columns c
		   JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
		  WHERE c.table_schema = $1 AND t.table_type IN ('BASE TABLE', 'VIEW')
		  ORDER BY c.table_name, c.ordinal_position`,
		[schemaName],
	);
	const byTable = new Map<string, ColumnRow[]>();
	for (const row of rows) {
		if (LEDGER_TABLE_NAMES.includes(row.table_name)) continue;
		const columns = byTable.get(row.table_name) ?? [];
		columns.push(row);
		byTable.set(row.table_name, columns);
	}
	const tables = [...byTable.keys()].sort();
	const lines = [
		'// Generated by `npm run db types` from the database schema. Do not edit: run the command again.',
		'',
		"// Structurally equal to Kysely's `ColumnType`, `Generated` and `GeneratedAlways`, so this file needs no import",
		'// and `new Kysely<Tables>(…)` accepts it.',
		'export type ColumnType<S, I = S, U = S> = { readonly __select__: S; readonly __insert__: I; readonly __update__: U };',
		'export type Generated<T> = ColumnType<T, T | undefined, T>;',
		'export type GeneratedAlways<T> = ColumnType<T, never, never>;',
		'',
		'export interface Tables {',
	];
	for (const table of tables) {
		lines.push(`\t${key(table)}: {`);
		for (const column of byTable.get(table) ?? [])
			lines.push(`\t\t${key(column.column_name)}: ${columnType(column)};`);
		lines.push('\t};');
	}
	lines.push('}', '');
	return { text: lines.join('\n'), tables };
}

/** Where `types` and `migrate` write the `Tables` interface when no file is named. */
export const TYPES_FILE = 'cdk-blocks/database.types.ts';

/** Writes the `Tables` interface of `schema`, as the database reports it, to `out`. */
export async function writeTypes(
	engine: DatabaseEngine,
	schema: string,
	out: string,
): Promise<{ out: string; tables: string[] }> {
	const file = await generateTypes(engine, schema);
	mkdirSync(dirname(resolve(out)), { recursive: true });
	writeFileSync(out, file.text);
	return { out, tables: file.tables };
}
