/**
 * Database-level coverage for the `extensions` option (#234).
 *
 * The engine- and resolver-level tests (pglite-engine.test.ts,
 * pglite-extensions.test.ts) prove `PGliteEngine.create()` and
 * `resolveExtensions()` in isolation. This file drives the actual
 * `index.mock.ts` wiring — a full `Database` constructed WITH extensions —
 * which the isolated tests do not reach. In particular it covers `crud()`:
 * `crud()` captures `this.base` synchronously, so the earlier placeholder-swap
 * implementation froze the handlers to a discarded, closed engine. The
 * `crud() + extensions` test below is the regression guard for that bug — it
 * fails against the swap implementation and passes against the stable
 * LazyEngine.
 *
 * These tests need the optional peer package `@electric-sql/pglite-pgvector`
 * (a devDependency), so they load `vector` for real and run `CREATE EXTENSION`.
 */
import { test, afterEach } from 'node:test';
import assert from 'node:assert';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { Scope } from '@aws-blocks/core';
import { Database } from './index.mock.js';
import { sql } from '@aws-blocks/data-common';
import type { TableSchema } from './crud/types.js';

// Each Database persists to `.bb-data/{fullId}`; a unique scope id per test
// keeps data dirs from colliding. Track them for teardown.
const createdDataDirs: string[] = [];

function uniqueScope(): Scope {
  const scope = new Scope('ext-db-test-' + Math.random().toString(36).slice(2));
  return scope;
}

afterEach(() => {
  // Database writes under `.bb-data/`; remove the whole dir between tests.
  rmSync('.bb-data', { recursive: true, force: true });
  for (const dir of createdDataDirs.splice(0)) {
    rmSync(dir, { recursive: true, force: true });
  }
});

const vectorSchema: TableSchema = {
  items: {
    singular: 'item',
    plural: 'items',
    primaryKey: 'id',
    columns: ['id', 'label', 'embedding'],
    autoGenerated: [],
  },
};

test('Database with extensions: query path loads the extension (CREATE EXTENSION vector)', async () => {
  const db = new Database(uniqueScope(), 'main', { extensions: ['pgvector'] });
  // Proves the LazyEngine resolved the extension-loaded PGlite: without the
  // vector extension this CREATE EXTENSION fails.
  await db.execute(sql`CREATE EXTENSION IF NOT EXISTS vector`);
  await db.execute(sql`CREATE TABLE items (id TEXT PRIMARY KEY, embedding vector(3))`);
  await db.execute(sql`INSERT INTO items VALUES ('a', '[1,2,3]')`);
  const rows = await db.query<{ id: string }>(
    sql`SELECT id FROM items ORDER BY embedding <-> '[1,2,3]' LIMIT 1`,
  );
  assert.deepStrictEqual(rows, [{ id: 'a' }]);
});

test('Database with extensions: crud() handlers run against the extension engine (regression for the placeholder-swap bug)', async () => {
  const db = new Database(uniqueScope(), 'main', {
    extensions: ['pgvector'],
    schema: vectorSchema,
  });

  // crud() captures the base engine synchronously. The bug: it froze the
  // discarded placeholder (destroyed by the async swap), so every CRUD call
  // hit a closed PGlite. With the stable LazyEngine, the handlers resolve the
  // extension engine on first use.
  const crud = db.crud({
    tables: ['items'],
    auth: async () => ({ userId: 'u1', claims: { sub: 'u1' } }),
  });

  // Set up the table + extension through the same Database (same engine).
  await db.execute(sql`CREATE EXTENSION IF NOT EXISTS vector`);
  await db.execute(
    sql`CREATE TABLE items (id TEXT PRIMARY KEY, label TEXT NOT NULL, embedding vector(3))`,
  );
  // crud() routes through withRLS() → SET LOCAL ROLE authenticated; create the
  // role and grants so the RLS path has a valid role to assume.
  await db.execute(sql`DO $$ BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'authenticated') THEN
      CREATE ROLE authenticated NOLOGIN;
    END IF;
  END $$`);
  await db.execute(sql`GRANT USAGE ON SCHEMA public TO authenticated`);
  await db.execute(sql`GRANT SELECT, INSERT, UPDATE, DELETE ON items TO authenticated`);

  // The CRUD create/list must run against the extension-loaded engine, not a
  // closed placeholder. A regression throws QueryFailed here.
  const created = await crud.createItem({ id: 'x', label: 'hello', embedding: '[1,2,3]' });
  assert.strictEqual((created as { id: string }).id, 'x');

  const listed = await crud.listItems();
  assert.strictEqual(listed.length, 1);
  assert.strictEqual((listed[0] as { label: string }).label, 'hello');
});

test('Database with extensions + migrationsPath: migrations run against the extension engine', async () => {
  const migrationsDir = mkdtempSync(join(tmpdir(), 'bb-data-ext-mig-'));
  createdDataDirs.push(migrationsDir);
  // A migration that depends on the extension being loaded: CREATE EXTENSION
  // then a table with a vector column. This only succeeds if migrations run
  // against the extension-loaded engine.
  writeFileSync(
    join(migrationsDir, '001_init.sql'),
    'CREATE EXTENSION IF NOT EXISTS vector;\n' +
      'CREATE TABLE docs (id TEXT PRIMARY KEY, embedding vector(3));\n' +
      "INSERT INTO docs VALUES ('d1', '[1,1,1]');\n",
  );

  const db = new Database(uniqueScope(), 'main', {
    extensions: ['pgvector'],
    migrationsPath: migrationsDir,
  });

  // ensureMigrations() runs the migration lazily before this query.
  const rows = await db.query<{ id: string }>(sql`SELECT id FROM docs`);
  assert.deepStrictEqual(rows, [{ id: 'd1' }]);
});

test('Database with an unknown extension: fails on first interaction with an actionable error', async () => {
  const db = new Database(uniqueScope(), 'main', { extensions: ['not-a-real-ext'] });
  // The constructor does not throw (resolution is lazy); the error surfaces on
  // the first database interaction with the supported-names list.
  await assert.rejects(
    () => db.query(sql`SELECT 1`),
    /Unknown Database extension 'not-a-real-ext'.*Supported extensions/s,
  );
});
