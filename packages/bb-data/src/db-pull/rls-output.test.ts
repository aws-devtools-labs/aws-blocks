/**
 * Row-level security in `db pull` output: the generated metadata records each
 * table's RLS state (so `db.crud()` can refuse a table without it), and the
 * generated guide only names options that exist.
 */
import { test } from 'node:test';
import assert from 'node:assert';
import { generateMetaFile, generateMigrationGuide, generateIndexFile, type TableInfo } from '../db-pull.js';

const table: TableInfo = {
  name: 'notes',
  columns: [
    { table_name: 'notes', column_name: 'id', data_type: 'uuid', is_nullable: 'NO', column_default: 'gen_random_uuid()', ordinal_position: 1 },
    { table_name: 'notes', column_name: 'user_id', data_type: 'text', is_nullable: 'NO', column_default: null, ordinal_position: 2 },
  ],
  primaryKey: 'id',
  autoGenerated: ['id'],
  hasRls: true,
  missingGrants: false,
};

test('generated meta records rowLevelSecurity for each table', () => {
  const out = generateMetaFile([table]);
  assert.match(out, /notes: \{[^}]*rowLevelSecurity: true,/);
});

test("generated wiring sets rlsPolicy: 'enforce'", () => {
  const out = generateIndexFile([table], { runtimeConnString: 'postgres://x' });
  assert.ok(out.includes("rlsPolicy: 'enforce'"));
});

test('generated migration guide names no rlsPolicy value other than enforce', () => {
  const out = generateMigrationGuide([table], new Map());
  const values = [...out.matchAll(/rlsPolicy: '([a-z]+)'/g)].map(m => m[1]);
  assert.deepStrictEqual(values.filter(v => v !== 'enforce'), [], `guide mentions nonexistent rlsPolicy values: ${values}`);
  assert.ok(!out.includes("'bypass'"), "guide must not mention a 'bypass' policy");
});
