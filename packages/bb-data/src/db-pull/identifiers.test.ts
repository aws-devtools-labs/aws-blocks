import type { ColumnInfo, TableInfo } from './types.js';
import {
  IDENTIFIER_PATTERN,
  RESERVED_TYPE_NAMES,
  assertValidIdentifiers,
  isIdentifier,
  isPlainIdentifier,
  tsPropertyKey,
  tsStringLiteral,
} from './identifiers.js';
