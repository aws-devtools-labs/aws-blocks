import { describe, test } from 'node:test';
import assert from 'node:assert';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import ts from 'typescript';
import type { ColumnInfo, TableInfo } from './types.js';
import {
  IDENTIFIER_PATTERN,
  assertValidIdentifiers,
  isPlainIdentifier,
  tsPropertyKey,
  tsStringLiteral,
} from './identifiers.js';
import { generateMetaFile, generateMigrationGuide, generateTypesFile, writeTypesAndMeta } from './generate.js';

// Names that are not plain identifiers, one per character class the check rejects.
const UNSUPPORTED_NAMES: [label: string, name: string][] = [
  ['single quote', "it's"],
  ['double quote', 'say"hi'],
  ['backtick', 'tick`tock'],
  // biome-ignore lint/suspicious/noTemplateCurlyInString: the literal `${b}` text is the case under test
  ['template placeholder', 'a${b}'],
  ['backslash', 'back\\slash'],
  ['newline', 'line\nbreak'],
  ['comment terminator', 'end*/x'],
  ['space', 'has space'],
  ['leading digit', '1st'],
  ['hyphen', 'kebab-case'],
  ['non-ASCII letter', 'café'],
  ['empty', ''],
];

function col(table: string, name: string, pos = 1): ColumnInfo {
  return {
    table_name: table,
    column_name: name,
    data_type: 'text',
    is_nullable: 'NO',
    column_default: null,
    ordinal_position: pos,
  };
}

function table(name: string, overrides: Partial<TableInfo> = {}): TableInfo {
  return {
    name,
    columns: [col(name, 'id'), col(name, 'title', 2)],
    primaryKey: 'id',
    autoGenerated: [],
    hasRls: true,
    missingGrants: false,
    ...overrides,
  };
}

/** Parse `source` as TypeScript and return its syntax diagnostics. */
function syntaxErrors(source: string): string[] {
  const out = ts.transpileModule(source, { reportDiagnostics: true, compilerOptions: { target: ts.ScriptTarget.ES2022 } });
  return (out.diagnostics ?? []).map(d => ts.flattenDiagnosticMessageText(d.messageText, '\n'));
}

/** Parse `const x = <literal>;` with the TypeScript parser and return the literal's value. */
function parseStringLiteral(literal: string): string {
  const sf = ts.createSourceFile('x.ts', `const x = ${literal};`, ts.ScriptTarget.ES2022);
  const stmt = sf.statements[0];
  assert.ok(ts.isVariableStatement(stmt));
  const init = stmt.declarationList.declarations[0].initializer;
  assert.ok(init && ts.isStringLiteral(init), `expected a single string literal, got: ${literal}`);
  return init.text;
}

/** Parse `interface X { <key>: string }` and return the property name as TypeScript sees it. */
function parseInterfaceKey(key: string): string {
  const sf = ts.createSourceFile('x.ts', `interface X { ${key}: string; }`, ts.ScriptTarget.ES2022);
  const decl = sf.statements[0];
  assert.ok(ts.isInterfaceDeclaration(decl));
  assert.equal(decl.members.length, 1, `expected exactly one member for key: ${key}`);
  const name = decl.members[0].name;
  assert.ok(name && (ts.isIdentifier(name) || ts.isStringLiteral(name)));
  return name.text;
}

/** Parse `({ <key>: 1 })` and return the property name as TypeScript sees it. */
function parseObjectKey(key: string): string {
  const sf = ts.createSourceFile('x.ts', `const o = { ${key}: 1 };`, ts.ScriptTarget.ES2022);
  const stmt = sf.statements[0];
  assert.ok(ts.isVariableStatement(stmt));
  const init = stmt.declarationList.declarations[0].initializer;
  assert.ok(init && ts.isObjectLiteralExpression(init));
  assert.equal(init.properties.length, 1, `expected exactly one property for key: ${key}`);
  const name = init.properties[0].name;
  assert.ok(name && (ts.isIdentifier(name) || ts.isStringLiteral(name)));
  return name.text;
}

describe('isPlainIdentifier', () => {
  test('accepts letters, digits and underscores not starting with a digit', () => {
    for (const name of ['id', 'user_id', '_private', 'CamelCase', 'a1', 'A']) {
      assert.equal(isPlainIdentifier(name), true, name);
    }
  });

  test('rejects every other name', () => {
    for (const [label, name] of UNSUPPORTED_NAMES) {
      assert.equal(isPlainIdentifier(name), false, label);
    }
  });

  test('the pattern is the documented one', () => {
    assert.equal(IDENTIFIER_PATTERN.source, '^[A-Za-z_][A-Za-z0-9_]*$');
  });
});

describe('tsStringLiteral', () => {
  test('keeps the single-quoted form for plain identifiers (generated files do not change)', () => {
    assert.equal(tsStringLiteral('user_id'), "'user_id'");
  });

  test('round-trips any string through the TypeScript parser', () => {
    for (const [label, name] of [...UNSUPPORTED_NAMES, ['line separator', 'a\u2028b'], ['tab', 'a\tb']] as const) {
      const literal = tsStringLiteral(name);
      assert.equal(parseStringLiteral(literal), name, label);
    }
  });
});

describe('tsPropertyKey', () => {
  test('keeps a bare key for plain identifiers, including reserved words', () => {
    assert.equal(tsPropertyKey('title'), 'title');
    assert.equal(tsPropertyKey('class'), 'class');
    assert.equal(parseInterfaceKey('class'), 'class');
  });

  test('quotes other names so they round-trip as one interface property and one object key', () => {
    for (const [label, name] of UNSUPPORTED_NAMES) {
      const key = tsPropertyKey(name);
      assert.notEqual(key, name, `${label} is quoted`);
      assert.equal(parseInterfaceKey(key), name, `${label} (interface)`);
      assert.equal(parseObjectKey(key), name, `${label} (object literal)`);
    }
  });
});

describe('assertValidIdentifiers', () => {
  test('accepts plain names', () => {
    assert.doesNotThrow(() => assertValidIdentifiers([table('todos'), table('Mixed_Case')]));
  });

  for (const [label, name] of UNSUPPORTED_NAMES) {
    test(`rejects a table name with ${label}, naming it and the allowed pattern`, () => {
      assert.throws(
        () => assertValidIdentifiers([table(name)]),
        (err: Error) =>
          err.message.includes(`table ${JSON.stringify(name)}`) && err.message.includes(IDENTIFIER_PATTERN.source),
      );
    });

    test(`rejects a column name with ${label}, naming the column and its table`, () => {
      const t = table('todos', { columns: [col('todos', 'id'), col('todos', name, 2)] });
      assert.throws(
        () => assertValidIdentifiers([t]),
        (err: Error) =>
          err.message.includes(`column ${JSON.stringify(name)} in table "todos"`) &&
          err.message.includes(IDENTIFIER_PATTERN.source),
      );
    });
  }

  test('rejects an unsupported primary key column (single and composite)', () => {
    for (const primaryKey of ['bad key', ['id', 'bad key']]) {
      assert.throws(
        () => assertValidIdentifiers([table('todos', { primaryKey })]),
        /primary key column "bad key" in table "todos"/,
      );
    }
  });

  test('rejects an unsupported autoGenerated column', () => {
    assert.throws(
      () => assertValidIdentifiers([table('todos', { autoGenerated: ["x'y"] })]),
      /autoGenerated column "x'y" in table "todos"/,
    );
  });

  test('rejects the reserved table name __proto__', () => {
    assert.throws(
      () => assertValidIdentifiers([table('__proto__')]),
      (err: Error) => err.message.includes('table "__proto__"') && err.message.includes('reserved name'),
    );
  });

  test('accepts __proto__ as a column name (columns are not object-literal keys in generated code)', () => {
    const t = table('todos', { columns: [col('todos', 'id'), col('todos', '__proto__', 2)] });
    assert.doesNotThrow(() => assertValidIdentifiers([t]));
    assert.deepEqual(syntaxErrors(generateTypesFile([t])), []);
    assert.deepEqual(syntaxErrors(generateMetaFile([t])), []);
  });

  test('rejects a table whose derived type name is not a valid identifier', () => {
    // `_1` matches the pattern, but PascalCase drops the underscore → `1`.
    assert.throws(() => assertValidIdentifiers([table('_1')]), /type name "1"/);
  });

  test('rejects a hand-edited singular that is not a plain identifier', () => {
    const singulars = new Map([['todos', "to'do"]]);
    assert.throws(() => assertValidIdentifiers([table('todos')], singulars), /singular "to'do"/);
  });
});

describe('generators check names before emitting', () => {
  for (const [label, name] of UNSUPPORTED_NAMES) {
    test(`generateTypesFile, generateMetaFile and generateMigrationGuide throw on a column with ${label}`, () => {
      const tables = [table('todos', { columns: [col('todos', 'id'), col('todos', name, 2)] })];
      const expected = (err: Error) => err.message.includes(JSON.stringify(name));
      assert.throws(() => generateTypesFile(tables), expected);
      assert.throws(() => generateMetaFile(tables), expected);
      assert.throws(() => generateMigrationGuide(tables, new Map()), expected);
    });
  }

  test('writeTypesAndMeta writes nothing when a name is rejected', () => {
    const dir = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'db-pull-ident-')), 'out');
    try {
      assert.throws(() => writeTypesAndMeta(dir, [table('has space')]), /table "has space"/);
      assert.equal(fs.existsSync(dir), false);
    } finally {
      fs.rmSync(path.dirname(dir), { recursive: true, force: true });
    }
  });

  test('generated types and meta for plain names parse without syntax errors', () => {
    const tables = [
      table('todos', { autoGenerated: ['id'] }),
      table('enrollments', {
        columns: [col('enrollments', 'student_id'), col('enrollments', 'course_id', 2)],
        primaryKey: ['student_id', 'course_id'],
      }),
    ];
    assert.deepEqual(syntaxErrors(generateTypesFile(tables)), []);
    assert.deepEqual(syntaxErrors(generateMetaFile(tables)), []);
  });
});
