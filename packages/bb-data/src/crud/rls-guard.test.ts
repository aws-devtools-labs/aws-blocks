/**
 * Row-level security guard for `db.crud()`.
 *
 * Generated CRUD scopes rows to the caller only through Postgres row-level
 * security: every handler runs as the `authenticated` role through
 * `withRLS()`, and Postgres filters nothing on a table without RLS. These tests
 * pin that CRUD refuses to run unscoped when the database or the table
 * metadata says RLS is required, and warns when it cannot tell.
 *
 * Runs through the local (PGlite) `Database`, the same path as `npm run dev`.
 */
import { test, after, afterEach, mock } from 'node:test';
import assert from 'node:assert';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Scope, isBlocksError } from '@aws-blocks/core';
import { sql } from '@aws-blocks/data-common';
import { createLambdaHandler } from '@aws-blocks/core/lambda-handler';
import { Database, DatabaseErrors } from '../index.mock.js';
import type { DatabaseOptions } from '../types.js';
import type { RLSEnabledDatabase } from '../database.js';
import { assertCrudRowLevelSecurity } from './rls-guard.js';
import type { TableSchema } from './types.js';

// Each Database persists to `.bb-data/{fullId}` under the cwd. Test files run
// in parallel processes that share the package dir, and some clear all of
// `.bb-data` between tests, so run this file from its own temp dir.
const workDir = mkdtempSync(join(tmpdir(), 'bb-data-rls-guard-'));
process.chdir(workDir);

afterEach(() => {
  mock.restoreAll();
});

after(() => {
  rmSync(workDir, { recursive: true, force: true });
});

const columns = ['id', 'content', 'user_id'] as const;

/** Meta as written before the row-level-security field existed. */
const legacyMeta = {
  notes: { singular: 'note', plural: 'notes', primaryKey: 'id', columns, autoGenerated: [] },
};

/** Meta whose author recorded the table as having row-level security. */
const rlsMeta = {
  notes: { singular: 'note', plural: 'notes', primaryKey: 'id', columns, autoGenerated: [], rowLevelSecurity: true },
};

/** Meta whose author recorded the table as NOT having row-level security. */
const noRlsMeta = {
  notes: { singular: 'note', plural: 'notes', primaryKey: 'id', columns, autoGenerated: [], rowLevelSecurity: false },
};

type NotesMeta = {
  notes: { row: { id: string; content: string; user_id: string }; singular: 'note'; plural: 'notes'; autoGenerated: never };
};

function newDb(schema: TableSchema, extra: Omit<DatabaseOptions, 'schema'> = {}): Database {
  const scope = new Scope(`rls-guard-${Math.random().toString(36).slice(2)}`);
  return new Database(scope, 'db', { schema, ...extra });
}

/** Create the `authenticated` role, a `notes` table with two users' rows, and grants. */
async function seed(db: Database, opts: { rls: boolean }): Promise<void> {
  await db.execute(sql`DO $$ BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'authenticated') THEN
      CREATE ROLE authenticated NOLOGIN;
    END IF;
  END $$`);
  await db.execute(sql`GRANT USAGE ON SCHEMA public TO authenticated`);
  await db.execute(sql`CREATE TABLE notes (id TEXT PRIMARY KEY, content TEXT NOT NULL, user_id TEXT NOT NULL)`);
  await db.execute(sql`GRANT SELECT, INSERT, UPDATE, DELETE ON notes TO authenticated`);
  if (opts.rls) {
    await db.execute(sql`ALTER TABLE notes ENABLE ROW LEVEL SECURITY`);
    await db.execute(sql`CREATE POLICY own_notes ON notes FOR ALL TO authenticated
      USING (user_id = (current_setting('request.jwt.claims', true)::json->>'sub'))
      WITH CHECK (user_id = (current_setting('request.jwt.claims', true)::json->>'sub'))`);
  }
  await db.execute(sql`INSERT INTO notes VALUES ('a1', 'alice note', 'alice'), ('b1', 'bob note', 'bob')`);
}

function crudFor(db: Database, userId: string) {
  return db.crud<NotesMeta>({ tables: ['notes'], auth: async () => ({ userId }) });
}

function isRlsRequired(e: unknown): boolean {
  return isBlocksError(e, DatabaseErrors.RowLevelSecurityRequired);
}

async function countRows(db: Database): Promise<number> {
  const rows = await db.query<{ n: number }>(sql`SELECT count(*)::int AS n FROM notes`);
  return rows[0].n;
}

test("rlsPolicy 'enforce': CRUD on a table without row-level security is refused before any read or write", async () => {
  const db = newDb(legacyMeta, { rlsPolicy: 'enforce' });
  await seed(db, { rls: false });
  const crud = crudFor(db, 'alice');

  await assert.rejects(crud.listNotes(), isRlsRequired);
  await assert.rejects(crud.getNote('b1'), isRlsRequired);
  await assert.rejects(crud.createNote({ id: 'x', content: 'x', user_id: 'alice' }), isRlsRequired);
  await assert.rejects(crud.updateNote('b1', { content: 'pwned' }), isRlsRequired);
  await assert.rejects(crud.deleteNote('b1'), isRlsRequired);

  assert.strictEqual(await countRows(db), 2, 'no row was written or deleted');
  const [bob] = await db.query<{ content: string }>(sql`SELECT content FROM notes WHERE id = 'b1'`);
  assert.strictEqual(bob.content, 'bob note', "another user's row was not modified");
});

test("rlsPolicy 'enforce': CRUD on a table with row-level security runs scoped to the caller", async () => {
  const db = newDb(legacyMeta, { rlsPolicy: 'enforce' });
  await seed(db, { rls: true });
  const rows = await crudFor(db, 'alice').listNotes();
  assert.deepStrictEqual(rows.map(r => r.id), ['a1']);
});

test('meta rowLevelSecurity: false is refused without an explicit acknowledgement', async () => {
  const schema: TableSchema = noRlsMeta;
  const db = newDb(schema);
  await seed(db, { rls: false });
  const crud = crudFor(db, 'alice');

  await assert.rejects(crud.listNotes(), isRlsRequired);
  await assert.rejects(crud.deleteNote('b1'), isRlsRequired);
  assert.strictEqual(await countRows(db), 2);
});

test('meta rowLevelSecurity: true, but RLS was disabled on the table afterwards, is refused', async () => {
  const schema: TableSchema = rlsMeta;
  const db = newDb(schema);
  await seed(db, { rls: true });
  await db.execute(sql`ALTER TABLE notes DISABLE ROW LEVEL SECURITY`);

  await assert.rejects(crudFor(db, 'alice').listNotes(), isRlsRequired);
  await assert.rejects(crudFor(db, 'alice').updateNote('b1', { content: 'pwned' }), isRlsRequired);
  const [bob] = await db.query<{ content: string }>(sql`SELECT content FROM notes WHERE id = 'b1'`);
  assert.strictEqual(bob.content, 'bob note');
});

test('meta without the rowLevelSecurity field, on a table without RLS: CRUD still runs but warns loudly', async () => {
  const warn = mock.method(console, 'warn', () => {});
  const db = newDb(legacyMeta);
  await seed(db, { rls: false });

  const rows = await crudFor(db, 'alice').listNotes();
  assert.strictEqual(rows.length, 2, 'unchanged behavior for existing metadata');

  const messages = warn.mock.calls.map(c => String(c.arguments[0]));
  const hit = messages.find(m => m.includes('row-level security') && m.includes('"notes"'));
  assert.ok(hit, `expected a row-level security warning naming the table, got: ${JSON.stringify(messages)}`);
});

test('dangerouslyAllowWithoutRowLevelSecurity serves a listed table without RLS, even under enforce, without warning', async () => {
  const warn = mock.method(console, 'warn', () => {});
  const schema: TableSchema = noRlsMeta;
  const db = newDb(schema, { rlsPolicy: 'enforce' });
  await seed(db, { rls: false });
  const crud = db.crud<NotesMeta>({
    tables: ['notes'],
    auth: async () => ({ userId: 'alice' }),
    dangerouslyAllowWithoutRowLevelSecurity: ['notes'],
  });
  const rows = await crud.listNotes();
  assert.strictEqual(rows.length, 2);
  assert.strictEqual(warn.mock.callCount(), 0);
});

test("rlsPolicy 'enforce': a table the authenticated role owns without FORCE ROW LEVEL SECURITY is refused", async () => {
  const db = newDb(legacyMeta, { rlsPolicy: 'enforce' });
  await seed(db, { rls: true });
  // The owner skips RLS unless it is forced, so this table is unscoped for CRUD.
  await db.execute(sql`ALTER TABLE notes OWNER TO authenticated`);
  await assert.rejects(crudFor(db, 'alice').listNotes(), isRlsRequired);
});

test("rlsPolicy 'enforce': the same owned table with FORCE ROW LEVEL SECURITY is served, scoped", async () => {
  const db = newDb(legacyMeta, { rlsPolicy: 'enforce' });
  await seed(db, { rls: true });
  await db.execute(sql`ALTER TABLE notes OWNER TO authenticated`);
  await db.execute(sql`ALTER TABLE notes FORCE ROW LEVEL SECURITY`);
  const rows = await crudFor(db, 'alice').listNotes();
  assert.deepStrictEqual(rows.map(r => r.id), ['a1']);
});

test('the refusal crosses the RPC wire as a named error, and only the server log names the table', async () => {
  const error = mock.method(console, 'error', () => {});
  mock.method(console, 'debug', () => {});
  const db = newDb(legacyMeta, { rlsPolicy: 'enforce' });
  await seed(db, { rls: false });
  const crud = crudFor(db, 'alice');

  const handler = createLambdaHandler(async () => ({ api: () => ({ run: () => crud.listNotes() }) }));
  const res = (await handler({
    httpMethod: 'POST',
    path: '/aws-blocks/api',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ jsonrpc: '2.0', method: 'api.run', params: [], id: 1 }),
    isBase64Encoded: false,
  } as never)) as { body: string };
  const body: { error?: { message: string; data?: { name?: string } } } = JSON.parse(res.body);

  assert.strictEqual(body.error?.data?.name, DatabaseErrors.RowLevelSecurityRequired);
  assert.ok(!res.body.includes('notes'), `the client-visible body does not name the table: ${res.body}`);
  const logged = error.mock.calls.map(c => String(c.arguments[0])).join('\n');
  assert.match(logged, /"notes"/, 'the server log names the table');
  assert.match(logged, /ENABLE ROW LEVEL SECURITY/, 'the server log shows the fix');
});

test("rlsPolicy 'enforce': a table the authenticated role owns through an inherited role membership is refused", async () => {
  const db = newDb(legacyMeta, { rlsPolicy: 'enforce' });
  await seed(db, { rls: true });
  // Postgres skips RLS for members of the owning role (INHERIT) too, not only
  // for the owner itself, so this table is unscoped for CRUD.
  await db.execute(sql`CREATE ROLE app_owner NOLOGIN`);
  await db.execute(sql`ALTER TABLE notes OWNER TO app_owner`);
  await db.execute(sql`GRANT app_owner TO authenticated`);
  // Precondition: the authenticated role really does see every row.
  const seen = await db.transaction(async tx => {
    await tx.execute(sql`SET LOCAL ROLE authenticated`);
    await tx.execute(sql`SELECT set_config('request.jwt.claims', '{"sub":"alice"}', true)`);
    return tx.query<{ id: string }>(sql`SELECT id FROM notes ORDER BY id`);
  });
  assert.deepStrictEqual(seen.map(r => r.id), ['a1', 'b1']);

  await assert.rejects(crudFor(db, 'alice').listNotes(), isRlsRequired);
});

test("rlsPolicy 'enforce': a missing table is refused rather than queried", async () => {
  mock.method(console, 'error', () => {});
  const db = newDb(legacyMeta, { rlsPolicy: 'enforce' });
  await db.execute(sql`SELECT 1`);
  await assert.rejects(crudFor(db, 'alice').listNotes(), isRlsRequired);
});

test("rlsPolicy 'enforce': enabling RLS after a refusal takes effect on the next call, on the same connection", async () => {
  mock.method(console, 'error', () => {});
  const db = newDb(legacyMeta, { rlsPolicy: 'enforce' });
  await seed(db, { rls: false });
  const crud = crudFor(db, 'alice');
  await assert.rejects(crud.listNotes(), isRlsRequired);

  // The fix the refusal log points to.
  await db.execute(sql`ALTER TABLE notes ENABLE ROW LEVEL SECURITY`);
  await db.execute(sql`CREATE POLICY own_notes ON notes FOR ALL TO authenticated
    USING (user_id = (current_setting('request.jwt.claims', true)::json->>'sub'))`);

  const rows = await crud.listNotes();
  assert.deepStrictEqual(rows.map(r => r.id), ['a1']);
});

test('compatibility path: a failed catalog read still serves the call', async () => {
  const fakeDb = {
    queryRaw: async () => {
      throw new Error('catalog read failed');
    },
  } as unknown as RLSEnabledDatabase;
  await assertCrudRowLevelSecurity(fakeDb, 'notes', legacyMeta.notes, {}, new Set());
});

test('a failed catalog read under enforce is not swallowed', async () => {
  const fakeDb = {
    queryRaw: async () => {
      throw new Error('catalog read failed');
    },
  } as unknown as RLSEnabledDatabase;
  await assert.rejects(
    assertCrudRowLevelSecurity(fakeDb, 'notes', legacyMeta.notes, { rlsPolicy: 'enforce' }, new Set()),
    /catalog read failed/,
  );
});
