import { type Server, createServer } from 'node:http';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOKEN_ENV_VAR, isAuthorized } from './auth.js';
import { PROFILE_ENV_VAR, REGION_ENV_VAR } from './aws-config.js';
import { ALLOWED_ORIGIN_ENV_VAR } from './http-guards.js';
import { PROJECT_ROOT_ENV_VAR } from './provider-registry.js';

export interface DashboardServerOptions {
	/** Root of the Blocks app the dashboard inspects. */
	projectRoot: string;
	/** Crypto-random session token generated by the CLI (per process). */
	token: string;
	/** Port to listen on. Default 4400. */
	port?: number;
	/** Run Next in dev (on-demand compile) mode. Default false. */
	dev?: boolean;
	/**
	 * Named AWS profile from the CLI's `--profile`. Exported as
	 * BLOCKS_DASHBOARD_PROFILE before Next boots, because route handlers resolve
	 * the profile per request (see aws-config.ts). Omitted or blank leaves the
	 * ambient AWS_PROFILE in force.
	 */
	profile?: string;
	/**
	 * AWS region from the CLI's `--region`. Exported as BLOCKS_DASHBOARD_REGION
	 * before Next boots, for the same per-request reason as `profile`. Omitted or
	 * blank leaves AWS_REGION / AWS_DEFAULT_REGION in force.
	 */
	region?: string;
	/**
	 * Extra browser origins from the CLI's `--allow-origin`. Exported as
	 * BLOCKS_DASHBOARD_ALLOWED_ORIGIN before Next boots, because the mutation
	 * guard reads it per request (see http-guards.ts). Needed when the dashboard
	 * is reached through a tunnel or any other reverse proxy, where the browser's
	 * `Origin` cannot match the loopback `Host` the server sees.
	 */
	allowedOrigins?: string[];
}

export interface DashboardServer {
	/** Base URL, e.g. http://127.0.0.1:4400 (token fragment NOT included). */
	url: string;
	port: number;
	close(): Promise<void>;
}

/**
 * Boots the Admin UI: a Next.js request handler wrapped in a plain
 * node:http server that (1) binds to 127.0.0.1 only and (2) rejects any
 * /api request without the session token — even if a route handler forgets
 * to check. Called by @aws-blocks/core's dashboard.ts via dynamic import.
 */
export async function startDashboardServer(options: DashboardServerOptions): Promise<DashboardServer> {
	const port = options.port ?? 4400;
	const hostname = '127.0.0.1';

	// Route handlers read these at request time (see provider-registry, auth).
	process.env[TOKEN_ENV_VAR] = options.token;
	process.env[PROJECT_ROOT_ENV_VAR] = options.projectRoot;

	// Same deal for the AWS identity (see aws-config.ts). Only set when a real
	// value was passed: assigning an empty string would shadow the ambient
	// AWS_PROFILE / AWS_REGION with a blank, which is worse than not setting it.
	if (options.profile?.trim()) process.env[PROFILE_ENV_VAR] = options.profile.trim();
	if (options.region?.trim()) process.env[REGION_ENV_VAR] = options.region.trim();

	// Same again for the declared origins, joined because the guard reads one
	// comma-separated variable. Blank entries are dropped here rather than
	// shipped for the reader to ignore.
	const declaredOrigins = (options.allowedOrigins ?? []).map((origin) => origin.trim()).filter(Boolean);
	if (declaredOrigins.length > 0) process.env[ALLOWED_ORIGIN_ENV_VAR] = declaredOrigins.join(',');

	// The Next app lives at this package's root (app/, .next/).
	const appDir = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

	// Lazy import: keeps `next` out of unit tests for the other modules.
	// Minimal local type: Next's own CJS types don't survive NodeNext interop.
	type CreateNextServer = (opts: { dev: boolean; dir: string; hostname: string; port: number }) => {
		prepare(): Promise<void>;
		getRequestHandler(): (
			req: import('node:http').IncomingMessage,
			res: import('node:http').ServerResponse,
		) => void;
	};
	const nextModule = (await import('next')) as unknown as {
		default: CreateNextServer | { default: CreateNextServer };
	};
	const createNext = typeof nextModule.default === 'function' ? nextModule.default : nextModule.default.default;
	const app = createNext({ dev: options.dev ?? false, dir: appDir, hostname, port });
	await app.prepare();
	const handle = app.getRequestHandler();

	const server: Server = createServer((req, res) => {
		if (req.url?.startsWith('/api/') && !isAuthorized(req.headers.authorization)) {
			res.statusCode = 401;
			res.setHeader('content-type', 'application/json');
			res.end(
				JSON.stringify({
					apiVersion: 1,
					error: { code: 'UNAUTHORIZED', message: 'Missing or invalid session token' },
				}),
			);
			return;
		}
		handle(req, res);
	});

	await new Promise<void>((resolve, reject) => {
		server.once('error', reject);
		server.listen(port, hostname, resolve);
	});

	return {
		url: `http://${hostname}:${port}`,
		port,
		close: () =>
			new Promise<void>((resolve, reject) => {
				server.close((err) => (err ? reject(err) : resolve()));
			}),
	};
}
