/** A `bin` command of the original package, rewired to run the vendorized source. */
export interface VendorBin {
  /** Command name, e.g. `bb-data`. */
  name: string;
  /** Shim the vendored package.json points `bin` at, relative to the package root. */
  shim: string;
  /** TypeScript entry the shim runs, relative to the package root (e.g. `./src/cli.ts`). */
  entry: string;
}

/** `tsx` range for a vendorized package with `bin` commands, when the app itself doesn't declare tsx. */
export const DEFAULT_TSX_RANGE = '^4.7.0';

/**
 * Map the original package's `bin` commands onto the vendorized `src/`.
 *
 * Only `src/` is copied, so a bin that points into `dist/` is rewired to a
 * generated shim that runs the matching `src/` entry with tsx. Bins that
 * don't map onto `src/` are left out.
 */
export function vendorBins(original: any): VendorBin[] {
  const bin: Record<string, string> =
    typeof original.bin === 'string'
      ? { [String(original.name).replace(/^@[^/]+\//, '')]: original.bin }
      : original.bin ?? {};
  const bins: VendorBin[] = [];
  for (const [name, target] of Object.entries(bin)) {
    const entry = remapPath(target.startsWith('./') ? target : `./${target}`);
    if (entry.startsWith('./src/')) bins.push({ name, shim: `./bin/${name}.js`, entry });
  }
  return bins;
}

/** Contents of the shim (at `bin.shim`) that runs a vendorized `bin` entry from source with tsx. */
export function generateBinShim(bin: VendorBin): string {
  // The entry is imported dynamically: a static import would be hoisted above register().
  return `#!/usr/bin/env node
// Generated by blocks-vendorize: runs the vendorized TypeScript source with tsx.
import { register } from 'tsx/esm/api';

register();
await import('.${bin.entry}');
`;
}

/**
 * Generate the vendorized package.json with exports remapped from dist/ to src/.
 *
 * Keeps the `@types/*` devDependencies the source needs to type-check, and
 * points each of `bins` at its shim, adding the `tsx` dependency the shims
 * run on (at `tsxRange`).
 */
export function generatePackageJson(original: any, bins: VendorBin[] = [], tsxRange = DEFAULT_TSX_RANGE): object {
  const pkg: any = {
    name: original.name,
    version: original.version,
    type: 'module',
    private: true,
    exports: remapExports(original.exports),
  };
  if (bins.length > 0) pkg.bin = Object.fromEntries(bins.map(b => [b.name, b.shim]));
  const dependencies = { ...original.dependencies };
  if (bins.length > 0 && !dependencies.tsx) dependencies.tsx = tsxRange;
  if (Object.keys(dependencies).length > 0) pkg.dependencies = dependencies;
  if (original.peerDependencies) pkg.peerDependencies = original.peerDependencies;
  const typeDeps = Object.entries(original.devDependencies ?? {}).filter(([name]) => name.startsWith('@types/'));
  if (typeDeps.length > 0) pkg.devDependencies = Object.fromEntries(typeDeps);
  return pkg;
}

/** Generate a tsconfig for building the vendorized source. */
export function generateTsconfig(): object {
  return {
    compilerOptions: {
      target: 'ES2022',
      module: 'NodeNext',
      moduleResolution: 'NodeNext',
      declaration: true,
      declarationMap: true,
      sourceMap: true,
      outDir: './dist',
      rootDir: './src',
      strict: true,
      esModuleInterop: true,
      skipLibCheck: true,
      forceConsistentCasingInFileNames: true,
    },
    include: ['src/**/*'],
  };
}

function remapExports(exports: any): any {
  if (!exports) return exports;
  if (typeof exports === 'string') return remapPath(exports);
  if (Array.isArray(exports)) return exports.map(remapExports);

  const result: any = {};
  for (const [key, value] of Object.entries(exports)) {
    if (typeof value === 'string') {
      result[key] = remapPath(value);
    } else if (typeof value === 'object' && value !== null) {
      result[key] = remapExports(value);
    } else {
      result[key] = value;
    }
  }
  return result;
}

function remapPath(p: string): string {
  if (p.startsWith('./dist/')) {
    const rest = p.slice('./dist/'.length);
    return `./src/${rest.replace(/\.d\.ts$/, '.ts').replace(/\.js$/, '.ts')}`;
  }
  return p;
}
