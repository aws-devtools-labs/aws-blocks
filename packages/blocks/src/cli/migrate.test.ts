/** Write a fixture app to a fresh temporary directory; returns its root. */
function writeApp(name: string, edit?: (app: FixtureApp) => void): string {
	const app = structuredClone(FIXTURES[name]);
	assert.ok(app, `fixture ${name} exists`);
	if (!SCAFFOLDED_BEFORE_STACK_ID.includes(name))
		app.files['.blocks/config.json'] = `${JSON.stringify({ stackId: 'my-app-a1b2c3' }, null, 2)}\n`;
	edit?.(app);
	const root = mkdtempSync(join(tmpdir(), 'blocks-migrate-'));
	writeFileSync(join(root, 'package.json'), `${JSON.stringify(app.packageJson, null, 2)}\n`);
	mkdirSync(join(root, 'aws-blocks'), { recursive: true });
	writeFileSync(join(root, 'aws-blocks', 'index.ts'), 'export {};\n');
	for (const [path, text] of Object.entries(app.files)) {
		mkdirSync(dirname(join(root, path)), { recursive: true });
		writeFileSync(join(root, path), text);
	}
	return root;
}

function readPkg(root: string): { scripts: Record<string, string>; blocks?: { dev?: unknown } } {
	return JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8'));
}

function scriptsDir(root: string): string[] {
	const dir = join(root, 'aws-blocks', 'scripts');
	return existsSync(dir) ? readdirSync(dir).sort() : [];
}

/**
 * A snapshot of every file under `root` outside `.git`, for "wrote nothing" checks.
 * Git owns `.git` and may change it on its own; a file that vanishes mid-walk is skipped.
 */
function snapshot(root: string): Record<string, string> {
	const files: Record<string, string> = {};
	const walk = (dir: string): void => {
		for (const name of readdirSync(dir, { withFileTypes: true })) {
			if (name.name === '.git') continue;
			const path = join(dir, name.name);
			if (name.isDirectory()) walk(path);
			else {
				try {
					files[path.slice(root.length)] = readFileSync(path, 'utf-8');
				} catch (error) {
					if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
				}
			}
		}
	};
	walk(root);
	return files;
}

function git(root: string, ...args: string[]): void {
	const config = ['-c', 'user.email=test@example.com', '-c', 'user.name=test', '-c', 'commit.gpgsign=false'];
	// `git submodule add` of a local path needs the file protocol, which git disallows by default.
	config.push('-c', 'protocol.file.allow=always');
	execFileSync('git', [...config, ...args], {
		cwd: root,
		stdio: 'ignore',
	});
}

/** Write `files` to a fresh temporary directory; returns it. */
function writeRepo(prefix: string, files: Record<string, string>): string {
	const top = mkdtempSync(join(tmpdir(), prefix));
	for (const [path, text] of Object.entries(files)) {
		mkdirSync(dirname(join(top, path)), { recursive: true });
		writeFileSync(join(top, path), text);
	}
	return top;
}

/** A committed monorepo with `files` and a `default@0ab6b047` app at `apps/<name>` for each of `apps`; returns its top. */
function monorepo(files: Record<string, string>, apps: readonly string[] = ['web']): string {
	const mono = writeRepo('blocks-migrate-mono-', files);
	mkdirSync(join(mono, 'apps'), { recursive: true });
	for (const name of apps) renameSync(writeApp('default@0ab6b047'), join(mono, 'apps', name));
	git(mono, 'init', '-q');
	git(mono, 'add', '-A');
	git(mono, 'commit', '-q', '-m', 'mono');
	return mono;
}

/** The sorted `[file, reason]` pairs of the `kept` items in a `--output json` result. */
function keptReasons(stdout: string): [string, string][] {
	const kept = JSON.parse(stdout).kept as { file: string; reason: string }[];
	return kept.map((k): [string, string] => [k.file, k.reason]).sort();
}

