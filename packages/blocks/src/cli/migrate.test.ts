interface FixtureApp {
	packageJson: { scripts: Record<string, string>; [key: string]: unknown };
	files: Record<string, string>;
}

/** Apps generated by create-blocks-app templates in git history; see the file's `_comment`. */
const FIXTURES = JSON.parse(
	readFileSync(fileURLToPath(new URL('../../test-fixtures/migrate-apps.json', import.meta.url)), 'utf-8'),
) as Record<string, FixtureApp>;

const TEMPLATES_DIR = fileURLToPath(new URL('../../../create-blocks-app/templates/', import.meta.url));

/** Write a fixture app to a fresh temporary directory; returns its root. */
function writeApp(name: string, edit?: (app: FixtureApp) => void): string {
	const app = structuredClone(FIXTURES[name]);
	assert.ok(app, `fixture ${name} exists`);
	edit?.(app);
	const root = mkdtempSync(join(tmpdir(), 'blocks-migrate-'));
	writeFileSync(join(root, 'package.json'), `${JSON.stringify(app.packageJson, null, 2)}\n`);
	mkdirSync(join(root, 'aws-blocks'), { recursive: true });
	writeFileSync(join(root, 'aws-blocks', 'index.ts'), 'export {};\n');
	for (const [path, text] of Object.entries(app.files)) {
		mkdirSync(dirname(join(root, path)), { recursive: true });
		writeFileSync(join(root, path), text);
	}
	return root;
}

function readPkg(root: string): { scripts: Record<string, string>; blocks?: { dev?: unknown } } {
	return JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8'));
}

function scriptsDir(root: string): string[] {
	const dir = join(root, 'aws-blocks', 'scripts');
	return existsSync(dir) ? readdirSync(dir).sort() : [];
}

/** A snapshot of every file under `root`, for "wrote nothing" checks. */
function snapshot(root: string): Record<string, string> {
	const files: Record<string, string> = {};
	const walk = (dir: string): void => {
		for (const name of readdirSync(dir, { withFileTypes: true })) {
			const path = join(dir, name.name);
			if (name.isDirectory()) walk(path);
			else files[path.slice(root.length)] = readFileSync(path, 'utf-8');
		}
	};
	walk(root);
	return files;
}

function git(root: string, ...args: string[]): void {
	const config = ['-c', 'user.email=test@example.com', '-c', 'user.name=test', '-c', 'commit.gpgsign=false'];
	execFileSync('git', [...config, ...args], {
		cwd: root,
		stdio: 'ignore',
	});
}

describe('blocks migrate references', () => {
	it('keeps a generated wrapper that a nested or parent-relative import still uses', async () => {
		const root = writeApp('api-only@0ab6b047', (app) => {
			app.files['aws-blocks/scripts/custom/run.ts'] = "import '../server.js';\n";
			app.files['test/deploy-helper.ts'] =
				"export const deploy = () => import('../aws-blocks/scripts/deploy');\n";
			app.files['aws-blocks/tools/stop.mjs'] = 'const stop = require(`../scripts/stop.ts`);\n';
		});
		const run = await runCli(['migrate', '--output', 'json'], { cwd: root });
		assert.strictEqual(run.code, 1, run.stderr);
		const kept = JSON.parse(run.stdout).kept as { file: string; reason: string }[];
		assert.deepStrictEqual(kept.map((k) => [k.file, k.reason]).sort(), [
			['aws-blocks/scripts/deploy.ts', 'generated, but still used by test/deploy-helper.ts'],
			['aws-blocks/scripts/server.ts', 'generated, but still used by aws-blocks/scripts/custom/run.ts'],
			['aws-blocks/scripts/stop.ts', 'generated, but still used by aws-blocks/tools/stop.mjs'],
		]);
		assert.deepStrictEqual(scriptsDir(root), ['custom', 'deploy.ts', 'server.ts', 'stop.ts']);
		// The scripts are still rewritten: only the files stay for the imports.
		assert.strictEqual(readPkg(root).scripts.deploy, 'blocks deploy');
	});

	it('does not mistake a longer name or another directory for a wrapper', async () => {
		const root = writeApp('api-only@0ab6b047', (app) => {
			app.files['aws-blocks/other/server.ts'] = 'export {};\n';
			app.files['aws-blocks/main.ts'] = "import './other/server.js';\nimport './scripts/sandbox-helpers.js';\n";
			app.files['aws-blocks/scripts/sandbox-helpers.ts'] = 'export {};\n';
		});
		const run = await runCli(['migrate', '--output', 'json'], { cwd: root });
		assert.strictEqual(run.code, 0, run.stdout);
		assert.deepStrictEqual(scriptsDir(root), ['sandbox-helpers.ts']);
	});
});

describe('blocks migrate', () => {
	it('migrates a pristine app from the last template version before the CLI', async () => {
		const root = writeApp('default@0ab6b047');
		const before = readPkg(root).scripts;
		const run = await runCli(['migrate', '--output', 'json'], { cwd: root });
		assert.strictEqual(run.code, 0, run.stderr);
		const result = JSON.parse(run.stdout);
		assert.deepStrictEqual(result.kept, []);
		assert.deepStrictEqual(result.changed, ['package.json']);
		const after = readPkg(root);
		assert.deepStrictEqual(after.scripts, {
			...before,
			'dev:server': 'blocks dev',
			dev: 'blocks dev',
			'dev:stop': 'blocks dev stop',
			sandbox: 'blocks sandbox',
			'sandbox:deploy': 'blocks sandbox deploy',
			'sandbox:destroy': 'blocks sandbox destroy',
			'sandbox:console': 'blocks sandbox console',
			cleanup: 'blocks dev stop --all',
			deploy: 'blocks deploy',
			secret: 'blocks secret',
			typegen: 'blocks generate types',
			destroy: 'blocks destroy',
		});
		assert.deepStrictEqual(result.scriptsRewritten.deploy, {
			from: 'tsx aws-blocks/scripts/deploy.ts',
			to: 'blocks deploy',
		});
		assert.deepStrictEqual(after.blocks, {
			dev: { frontendCommand: 'npx vite --port 3100 --strictPort', frontendPort: 3100 },
		});
		assert.deepStrictEqual(result.devConfig, after.blocks?.dev, 'the JSON reports the blocks.dev it wrote');
		assert.strictEqual(result.removed.length, 10);
		assert.ok(!existsSync(join(root, 'aws-blocks', 'scripts')), 'the emptied scripts directory is removed');
	});

	it('migrates the same app to what create-blocks-app now scaffolds', async () => {
		for (const template of ['default', 'api-only']) {
			const root = writeApp(`${template}@0ab6b047`);
			const run = await runCli(['migrate'], { cwd: root });
			assert.strictEqual(run.code, 0, run.stderr);
			const current = JSON.parse(readFileSync(join(TEMPLATES_DIR, template, 'package.json'), 'utf-8'));
			const migrated = readPkg(root);
			// spec and vendorize call bins, not wrappers; migrate leaves them as they are.
			const { spec: _a, vendorize: _b, ...expected } = current.scripts;
			const { spec: _c, vendorize: _d, ...actual } = migrated.scripts;
			assert.deepStrictEqual(actual, expected, template);
			assert.deepStrictEqual(migrated.blocks, current.blocks, template);
		}
	});

	it('migrates an app from the first template version and an old nextjs version', async () => {
		const backend = writeApp('backend@1aeebe50');
		const run = await runCli(['migrate'], { cwd: backend });
		assert.strictEqual(run.code, 0, run.stderr);
		assert.deepStrictEqual(readPkg(backend).blocks, { dev: { port: 3001, frontend: false } });
		assert.strictEqual(readPkg(backend).scripts.dev, 'blocks dev');
		// sandbox-id.ts is imported by index.cdk.ts and is not a lifecycle wrapper: left alone.
		assert.deepStrictEqual(scriptsDir(backend), ['sandbox-id.ts']);

		const nextjs = writeApp('nextjs@0ac38793');
		const next = await runCli(['migrate'], { cwd: nextjs });
		assert.strictEqual(next.code, 0, next.stderr);
		assert.deepStrictEqual(readPkg(nextjs).blocks, {
			dev: { frontendCommand: 'npx next dev --port 3100', frontendPort: 3100 },
		});
		assert.deepStrictEqual(scriptsDir(nextjs), []);
	});

	it('migrates the amplify overlay and keeps its client generator', async () => {
		const root = writeApp('amplify@0ab6b047');
		const run = await runCli(['migrate'], { cwd: root });
		assert.strictEqual(run.code, 0, run.stderr);
		const pkg = readPkg(root);
		assert.strictEqual(pkg.scripts['blocks:dev'], 'blocks dev');
		assert.strictEqual(pkg.scripts['blocks:stop'], 'blocks dev stop');
		assert.match(pkg.scripts['blocks:generate-client'], /tsx aws-blocks\/scripts\/generate-client\.ts$/);
		assert.deepStrictEqual(pkg.blocks, { dev: { port: 3001, frontend: false } });
		assert.deepStrictEqual(scriptsDir(root), ['generate-client.ts']);
	});

	it('keeps and reports a customized deploy.ts, and exits 1', async () => {
		const root = writeApp('api-only@0ab6b047', (app) => {
			app.files['aws-blocks/scripts/deploy.ts'] += "\nconsole.log('notify the team');\n";
		});
		const run = await runCli(['migrate', '--output', 'json'], { cwd: root });
		assert.strictEqual(run.code, 1);
		assert.doesNotMatch(run.stderr, /Error:/, 'remaining manual work is a report, not a crash');
		const result = JSON.parse(run.stdout);
		assert.deepStrictEqual(
			result.kept.map((k: { file: string }) => k.file),
			['aws-blocks/scripts/deploy.ts'],
		);
		assert.match(result.kept[0].reason, /customized/);
		const pkg = readPkg(root);
		assert.strictEqual(pkg.scripts.deploy, 'tsx aws-blocks/scripts/deploy.ts', 'its script still runs it');
		assert.strictEqual(pkg.scripts.destroy, 'blocks destroy');
		assert.deepStrictEqual(scriptsDir(root), ['deploy.ts']);

		const text = await runCli(['migrate'], { cwd: root });
		assert.strictEqual(text.code, 1);
		assert.match(text.stdout, /finish by hand/);
		assert.match(text.stdout, /aws-blocks\/scripts\/deploy\.ts: customized/);
	});

	for (const template of ['default@0ab6b047', 'api-only@0ab6b047']) {
		it(`keeps the sandbox scripts when server.ts is customized and sandbox.ts is generated (${template})`, async () => {
			// Every generated sandbox.ts starts server.ts as the sandbox's dev server
			// (devCommand in the frontend templates, core's default in api-only), so
			// rewriting `sandbox` to `blocks sandbox` would bypass the custom server.
			const root = writeApp(template, (app) => {
				app.files['aws-blocks/scripts/server.ts'] += "\nconsole.log('custom middleware');\n";
			});
			const before = readPkg(root).scripts;
			const run = await runCli(['migrate', '--output', 'json'], { cwd: root });
			assert.strictEqual(run.code, 1, run.stderr);
			const result = JSON.parse(run.stdout);
			const pkg = readPkg(root);
			for (const name of ['sandbox', 'sandbox:deploy', 'dev'] as const) {
				assert.strictEqual(pkg.scripts[name], before[name], `${name} still runs the wrappers`);
				assert.strictEqual(result.scriptsRewritten[name], undefined, `${name} was not rewritten`);
			}
			const kept = result.kept.map((k: { file: string }) => k.file);
			assert.ok(kept.includes('aws-blocks/scripts/server.ts'), 'the customized server is reported');
			assert.ok(kept.includes('package.json#scripts.sandbox'), 'the sandbox script is reported');
			assert.match(
				result.kept.find((k: { file: string }) => k.file === 'package.json#scripts.sandbox').reason,
				/customized aws-blocks\/scripts\/server\.ts/,
			);
			assert.strictEqual(result.devConfig, null, 'no dev config is derived from a customized server');
			assert.strictEqual(pkg.scripts.deploy, 'blocks deploy', 'unrelated scripts still migrate');
			const left = scriptsDir(root);
			assert.ok(left.includes('server.ts') && left.includes('sandbox.ts'), `kept wrappers: ${left.join(', ')}`);
		});
	}

	it('keeps a generated wrapper that a customized one still uses', async () => {
		const root = writeApp('default@0ab6b047', (app) => {
			app.files['aws-blocks/scripts/sandbox.ts'] = app.files['aws-blocks/scripts/sandbox.ts'].replace(
				"devCommand: 'npx tsx watch aws-blocks/scripts/server.ts',",
				"devCommand: 'npx tsx watch aws-blocks/scripts/server.ts', clientPort: 4000,",
			);
		});
		const run = await runCli(['migrate', '--output', 'json'], { cwd: root });
		assert.strictEqual(run.code, 1);
		const kept = JSON.parse(run.stdout).kept as { file: string; reason: string }[];
		assert.deepStrictEqual(kept.map((k) => k.file).sort(), [
			'aws-blocks/scripts/sandbox.ts',
			'aws-blocks/scripts/server.ts',
		]);
		assert.match(
			kept.find((k) => k.file.endsWith('server.ts'))?.reason ?? '',
			/used by aws-blocks\/scripts\/sandbox\.ts/,
		);
		assert.strictEqual(readPkg(root).scripts.sandbox, 'tsx aws-blocks/scripts/sandbox.ts');
		assert.strictEqual(readPkg(root).scripts.dev, 'blocks dev');
	});

	it('--dry-run writes nothing and prints the plan', async () => {
		const root = writeApp('default@0ab6b047');
		const before = snapshot(root);
		const run = await runCli(['migrate', '--dry-run'], { cwd: root });
		assert.strictEqual(run.code, 0, run.stderr);
		assert.deepStrictEqual(snapshot(root), before);
		assert.match(run.stdout, /^Dry run; nothing was written/);
		assert.match(run.stdout, /rewrite script "deploy": tsx aws-blocks\/scripts\/deploy\.ts -> blocks deploy/);
		assert.match(run.stdout, /delete aws-blocks\/scripts\/server\.ts/);
	});

	it('--dry-run --output json reports the devConfig it would add, and writes nothing', async () => {
		const root = writeApp('backend@1aeebe50');
		const before = snapshot(root);
		const run = await runCli(['migrate', '--dry-run', '--output', 'json'], { cwd: root });
		assert.strictEqual(run.code, 0, run.stderr);
		assert.deepStrictEqual(snapshot(root), before);
		const result = JSON.parse(run.stdout);
		assert.deepStrictEqual(result.devConfig, { port: 3001, frontend: false });
		assert.deepStrictEqual(result.changed, ['package.json']);
		assert.strictEqual(readPkg(root).blocks, undefined, 'package.json has no blocks.dev yet');
	});

	it('refuses a dirty git tree with exit 1 and a Try: hint, unless --force', async () => {
		const root = writeApp('api-only@0ab6b047');
		git(root, 'init', '-q');
		git(root, 'add', '-A');
		git(root, 'commit', '-q', '-m', 'init');
		writeFileSync(join(root, 'notes.txt'), 'uncommitted\n');
		const before = snapshot(root);
		const run = await runCli(['migrate'], { cwd: root });
		assert.strictEqual(run.code, 1);
		assert.match(run.stderr, /^Error: the git working tree has uncommitted changes/);
		assert.match(run.stderr, /\nTry: .*blocks migrate --force/);
		assert.deepStrictEqual(snapshot(root), before);

		const forced = await runCli(['migrate', '--force'], { cwd: root });
		assert.strictEqual(forced.code, 0, forced.stderr);
		assert.strictEqual(readPkg(root).scripts.deploy, 'blocks deploy');
	});

	it('runs in a clean git tree', async () => {
		const root = writeApp('api-only@0ab6b047');
		git(root, 'init', '-q');
		git(root, 'add', '-A');
		git(root, 'commit', '-q', '-m', 'init');
		const run = await runCli(['migrate'], { cwd: root });
		assert.strictEqual(run.code, 0, run.stderr);
	});

	it('leaves unrelated scripts and files untouched', async () => {
		const root = writeApp('default@0ab6b047', (app) => {
			app.packageJson.scripts['seed'] = 'tsx aws-blocks/scripts/seed.ts';
			app.packageJson.scripts['dev:debug'] = 'tsx watch --inspect aws-blocks/scripts/server.ts';
			app.packageJson.scripts['lint'] = 'biome check .';
			app.files['aws-blocks/scripts/seed.ts'] = "console.log('seed');\n";
		});
		const before = readPkg(root).scripts;
		const run = await runCli(['migrate', '--output', 'json'], { cwd: root });
		const result = JSON.parse(run.stdout);
		const after = readPkg(root).scripts;
		for (const name of [
			'seed',
			'dev:debug',
			'lint',
			'build',
			'preview',
			'test:e2e',
			'prebuild',
			'spec',
			'vendorize',
		]) {
			assert.strictEqual(after[name], before[name], name);
		}
		// dev:debug runs server.ts in a way migrate cannot rewrite, so server.ts stays and is reported.
		assert.strictEqual(run.code, 1);
		assert.deepStrictEqual(result.kept.map((k: { file: string }) => k.file).sort(), [
			'aws-blocks/scripts/server.ts',
			'package.json#scripts.dev:debug',
		]);
		assert.deepStrictEqual(scriptsDir(root), ['seed.ts', 'server.ts']);
	});

	it('is idempotent', async () => {
		const root = writeApp('default@0ab6b047');
		assert.strictEqual((await runCli(['migrate'], { cwd: root })).code, 0);
		const once = snapshot(root);
		const again = await runCli(['migrate', '--output', 'json'], { cwd: root });
		assert.strictEqual(again.code, 0, again.stderr);
		assert.deepStrictEqual(JSON.parse(again.stdout), {
			changed: [],
			removed: [],
			kept: [],
			scriptsRewritten: {},
			devConfig: null,
		});
		assert.deepStrictEqual(snapshot(root), once);
		const text = await runCli(['migrate', '--dry-run'], { cwd: root });
		assert.match(text.stdout, /^Nothing to migrate/);
	});

	it('does not overwrite an existing blocks.dev', async () => {
		const root = writeApp('default@0ab6b047', (app) => {
			app.packageJson.blocks = { dev: { port: 4000 } };
		});
		const run = await runCli(['migrate', '--output', 'json'], { cwd: root });
		assert.strictEqual(run.code, 0, run.stderr);
		assert.strictEqual(JSON.parse(run.stdout).devConfig, null);
		assert.deepStrictEqual(readPkg(root).blocks, { dev: { port: 4000 } });
	});

	it('knows every fixture wrapper and maps each generated command to a real blocks command', () => {
		for (const [name, app] of Object.entries(FIXTURES)) {
			if (name.startsWith('_')) continue;
			for (const [path, text] of Object.entries(app.files)) {
				const file = path.replace('aws-blocks/scripts/', '') as keyof typeof GENERATED_WRAPPERS;
				if (!(file in GENERATED_WRAPPERS)) continue;
				assert.ok(GENERATED_WRAPPERS[file].includes(sourceHash(text)), `${name}: ${path} is a known version`);
			}
		}
		for (const hash of GENERATED_WRAPPERS['server.ts']) assert.ok(hash in SERVER_DEV_OPTIONS, hash);
		for (const { alias } of Object.values(SCRIPT_REWRITES)) {
			const parsed = parseArgv(alias.split(' ').slice(1));
			assert.ok(parsed.command?.handler, `${alias} runs a command`);
		}
	});

	it('ignores whitespace differences when it classifies a wrapper', async () => {
		const root = writeApp('api-only@0ab6b047', (app) => {
			app.files['aws-blocks/scripts/deploy.ts'] = app.files['aws-blocks/scripts/deploy.ts']
				.replace(/\n/g, '\r\n')
				.replace(/ {2}/g, '\t');
		});
		const run = await runCli(['migrate'], { cwd: root });
		assert.strictEqual(run.code, 0, run.stdout);
		assert.strictEqual(readPkg(root).scripts.deploy, 'blocks deploy');
	});
});
