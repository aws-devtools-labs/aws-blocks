/**
 * `aws-cdk-blocks` — `browser` entry.
 *
 * A bundler (and `tsx -C browser`, which the templates' e2e tests use) resolves
 * `aws-cdk-blocks` here instead of to the backend entry. An app compiles against
 * the backend entry's types (`index.d.ts`), so every value here is one those
 * types already promise:
 *
 * - every Building Block's `*Errors` constants, so a frontend matches an error
 *   with `isBlocksError(e, KVStoreErrors.ConditionalCheckFailed)`, the same code
 *   as on the server (only the error name crosses the RPC wire);
 * - the values of core's browser entry that the backend entry exports too: the
 *   error class and matchers (`ApiError`, `isBlocksError`, …) and `Scope`;
 * - the pure helpers a block's browser build carries (`BedrockModels`,
 *   `isAuthError`, `stubIdp`, …).
 *
 * Each name comes from its package's root, whose `browser` condition resolves
 * that package's browser build. Those builds import no server code and no AWS
 * SDK, so neither reaches a browser bundle.
 *
 * The Building Block classes (`KVStore`, `Database`, …), `sql`, and the server
 * and CDK helpers are not here: they run on the server only, and browser code
 * uses `import type` for their types. `RawRouteErrors` is not here either: it
 * names an error thrown while a `RawRoute` is registered on the server, which
 * never reaches a client, and core's browser entry does not carry the route
 * registry it lives in. The API client runtime and the rest of core's
 * browser-safe values stay in `aws-cdk-blocks/client`.
 *
 * `umbrella-browser-exports.test.ts` keeps this list complete. It fails when the
 * backend entry exports an error constant or a client-safe value that is missing
 * here, when a name here is missing from the backend entry, and when a value
 * differs from the one in the package that defines it.
 */

