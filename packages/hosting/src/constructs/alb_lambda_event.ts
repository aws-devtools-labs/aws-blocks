/**
 * The ALB event shim for a native Lambda handler server (Nitro's `aws-lambda`
 * preset) behind the ALB door.
 *
 * An Application Load Balancer (ALB) invokes a Lambda target with its own
 * event shape. The ALB door turns multi-value headers on for the server target
 * group, so several `Set-Cookie` headers survive; the event then carries
 * `multiValueHeaders` and `multiValueQueryStringParameters` (query values still
 * URL-encoded), the method at the top level (`httpMethod`), and the response
 * must answer with `multiValueHeaders`. A handler written for API Gateway reads
 * `event.headers` and answers with `headers` (cookies in `multiValueHeaders` or
 * `cookies`), so behind the ALB it would see no headers and lose its cookies.
 *
 * The shim sits in front of the handler (the server's `handler` becomes
 * {@link ALB_EVENT_SHIM_HANDLER}): an ALB event is rewritten into the API
 * Gateway REST (payload 1.0) shape — `headers` and `multiValueHeaders`, decoded
 * query parameters, `requestContext.httpMethod` / `path` — and the response is
 * folded back into the ALB shape (every header and cookie as
 * `multiValueHeaders` when the event was multi-value, else single values, plus
 * `statusDescription`). Any other event reaches the handler unchanged.
 *
 * It is a small ES module written next to the handler at synth; it imports
 * only `node:http` (for the status text).
 *
 * @internal Framework-only.
 */

/** The shim's file name in the server bundle. */
export const ALB_EVENT_SHIM_FILE = 'blocks_alb_event.mjs';

/** The server's `handler` setting when the shim is in front of it. */
export const ALB_EVENT_SHIM_HANDLER = 'blocks_alb_event.handler';

/**
 * The shim's source.
 *
 * @param innerModule the handler's module, relative to the shim (e.g. `./index.mjs`).
 * @param innerExport the handler's export name. @default 'handler'
 * @returns the ES module source.
 */
export const generateAlbEventShimCode = (innerModule: string, innerExport = 'handler'): string => `// Generated by @aws-blocks/hosting: ALB Lambda-target events for an API Gateway-shaped handler.
import { STATUS_CODES } from 'node:http';
import * as inner from ${JSON.stringify(innerModule)};

const run = inner[${JSON.stringify(innerExport)}] || (inner.default && inner.default[${JSON.stringify(innerExport)}]);

function decode(s) {
  try { return decodeURIComponent(String(s).replace(/\\+/g, ' ')); } catch (e) { return String(s); }
}

function toRestEvent(event) {
  const multi = event.multiValueHeaders != null;
  const multiHeaders = {};
  const headers = {};
  if (multi) {
    for (const name in event.multiValueHeaders) {
      const key = name.toLowerCase();
      const values = [].concat(event.multiValueHeaders[name]).map(String);
      multiHeaders[key] = values;
      headers[key] = values.join(key === 'cookie' ? '; ' : ', ');
    }
  } else {
    for (const name in event.headers || {}) {
      const key = name.toLowerCase();
      headers[key] = String(event.headers[name]);
      multiHeaders[key] = [headers[key]];
    }
  }
  let query = null;
  let multiQuery = null;
  const rawQuery = event.multiValueQueryStringParameters || null;
  const single = event.queryStringParameters || null;
  if (rawQuery || single) {
    query = {};
    multiQuery = {};
    const source = rawQuery || Object.fromEntries(Object.entries(single).map(([k, v]) => [k, [v]]));
    for (const name in source) {
      const key = decode(name);
      const values = [].concat(source[name]).map(decode);
      multiQuery[key] = values;
      query[key] = values[values.length - 1];
    }
  }
  return {
    multi,
    event: {
      resource: '/{proxy+}',
      path: event.path,
      httpMethod: event.httpMethod,
      headers,
      multiValueHeaders: multiHeaders,
      queryStringParameters: query,
      multiValueQueryStringParameters: multiQuery,
      pathParameters: null,
      stageVariables: null,
      requestContext: Object.assign({}, event.requestContext, { httpMethod: event.httpMethod, path: event.path }),
      body: event.body == null ? null : event.body,
      isBase64Encoded: Boolean(event.isBase64Encoded),
    },
  };
}

function toAlbResponse(res, multi) {
  res = res || {};
  const out = {};
  for (const name in res.headers || {}) {
    const value = res.headers[name];
    if (value != null) out[name.toLowerCase()] = [].concat(value).map(String);
  }
  for (const name in res.multiValueHeaders || {}) {
    const values = [].concat(res.multiValueHeaders[name]).filter((v) => v != null).map(String);
    const key = name.toLowerCase();
    out[key] = key === 'set-cookie' ? (out[key] || []).concat(values) : values;
  }
  if (Array.isArray(res.cookies) && res.cookies.length > 0) {
    out['set-cookie'] = (out['set-cookie'] || []).concat(res.cookies.map(String));
  }
  const statusCode = res.statusCode || 200;
  const albResponse = {
    statusCode,
    statusDescription: (statusCode + ' ' + (STATUS_CODES[statusCode] || '')).trim(),
    isBase64Encoded: Boolean(res.isBase64Encoded),
    body: res.body == null ? '' : String(res.body),
  };
  if (multi) {
    albResponse.multiValueHeaders = out;
  } else {
    albResponse.headers = {};
    for (const key in out) albResponse.headers[key] = out[key][out[key].length - 1];
  }
  return albResponse;
}

export async function handler(event, context) {
  if (!event || !event.requestContext || !event.requestContext.elb) return run(event, context);
  const rest = toRestEvent(event);
  return toAlbResponse(await run(rest.event, context), rest.multi);
}
`;
