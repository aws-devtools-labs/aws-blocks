/**
 * The synth-time check of the physical names Building Blocks derive from
 * scope and block ids.
 *
 * A block names its resource from its `fullId`: the ids from the backend root
 * down, joined with `-` and not escaped. Nothing restricts an id, so
 * `new Scope('@acme/shop')` is accepted, and a `KVStore` under it synthesizes
 * a table named `<stack>-@acme/shop-<id>`. DynamoDB rejects that name when
 * CloudFormation creates the table, after which the stack rolls back.
 *
 * Which characters deploy depends on the resource: Secrets Manager accepts `@`
 * and `/` in a name, DynamoDB accepts neither, and a scope that only holds an
 * `ApiNamespace` names nothing from its id. An id is therefore not rejected
 * for its characters alone. Instead, each backend root validates the names
 * that reached the template: for every resource of a type in
 * {@link NAME_RULES} under a `Scope`, a literal name with a character its
 * service rejects fails synth, with an error that names the id the character
 * came from. A name that is generated by CloudFormation, or that resolves at
 * deploy, is not a string here and is left to the service.
 *
 * Only characters are checked. Length, and rules about where a character may
 * appear, stay with the block that builds the name (`FileBucket` validates its
 * bucket name, `Auth` the length of its user pool name).
 *
 * @module
 * @internal
 */

import * as cdk from 'aws-cdk-lib';
import type { Construct, IConstruct } from 'constructs';
import { getOrCreateOnRoot } from './root-registry.js';

/** How one CloudFormation resource type names its resource. */
interface NameRule {
	/** The CloudFormation property of the resource type that holds the physical name. */
	readonly property: string;
	/** The resource, as the error calls it. */
	readonly what: string;
	/** Matches one character the service accepts in the name. */
	readonly accepts: RegExp;
	/** The accepted characters, in words. */
	readonly acceptsText: string;
	/** A suffix the service requires on some names, outside the accepted characters (`.fifo`). */
	readonly suffix?: string;
}

const DYNAMODB_TABLE: NameRule = {
	property: 'TableName',
	what: 'DynamoDB table',
	accepts: /[A-Za-z0-9_.-]/,
	acceptsText: "letters, digits, '_', '.' and '-'",
};

const BEDROCK_NAME = { accepts: /[A-Za-z0-9_-]/, acceptsText: "letters, digits, '_' and '-'" };

/**
 * The resource types whose physical name a Building Block takes from `fullId`
 * (or from an explicit name option), with the characters each service
 * documents for that name in its API reference: `CreateTable` (DynamoDB),
 * `CreateQueue` (SQS), `CreateSchedule` (EventBridge Scheduler),
 * `CreateUserPool` (Cognito), `CreateSecret` (Secrets Manager),
 * `CreateKnowledgeBase` and `CreateDataSource` (Bedrock).
 *
 * Add a type here when a block starts naming a resource of it from `fullId`.
 * Types that are absent are not checked, because something else already does
 * or no check is needed: `aws-cdk-lib` rejects an invalid Systems Manager
 * parameter name when the `StringParameter` is constructed, `FileBucket`
 * validates its own bucket name, and a block that rewrites `fullId` into a
 * valid name (`Dashboard`, `Database`) cannot produce an invalid one.
 */
const NAME_RULES: Readonly<Record<string, NameRule>> = {
	'AWS::DynamoDB::Table': DYNAMODB_TABLE,
	'AWS::DynamoDB::GlobalTable': DYNAMODB_TABLE,
	'AWS::SQS::Queue': {
		property: 'QueueName',
		what: 'SQS queue',
		accepts: /[A-Za-z0-9_-]/,
		acceptsText: "letters, digits, '_' and '-'",
		suffix: '.fifo',
	},
	'AWS::Scheduler::Schedule': {
		property: 'Name',
		what: 'EventBridge Scheduler schedule',
		accepts: /[A-Za-z0-9_.-]/,
		acceptsText: "letters, digits, '_', '.' and '-'",
	},
	'AWS::Cognito::UserPool': {
		property: 'UserPoolName',
		what: 'Cognito user pool',
		// Documented as `[\w\s+=,.@-]+`. Any letter or digit is let through, in case
		// the service reads `\w` as more than ASCII.
		accepts: /[\p{L}\p{N}_\s+=,.@-]/u,
		acceptsText: "letters, digits, spaces, '_', '+', '=', ',', '.', '@' and '-'",
	},
	'AWS::SecretsManager::Secret': {
		property: 'Name',
		what: 'Secrets Manager secret',
		accepts: /[A-Za-z0-9/_+=.@-]/,
		acceptsText: "letters, digits, '/', '_', '+', '=', '.', '@' and '-'",
	},
	'AWS::Bedrock::KnowledgeBase': { property: 'Name', what: 'Bedrock knowledge base', ...BEDROCK_NAME },
	'AWS::Bedrock::DataSource': { property: 'Name', what: 'Bedrock data source', ...BEDROCK_NAME },
};

/**
 * A `CfnResource` as this check reads it. `_toCloudFormation()` renders the
 * resource as it reaches the template, raw overrides included; `aws-cdk-lib`
 * marks it internal, so it is not in the public typings.
 */
interface RenderableResource extends cdk.CfnResource {
	_toCloudFormation(): object;
}

function isRenderable(resource: cdk.CfnResource): resource is RenderableResource {
	return typeof (resource as Partial<RenderableResource>)._toCloudFormation === 'function';
}

/**
 * The physical name `resource` has in the rendered template, under the
 * CloudFormation property `property`, after its raw overrides. `undefined`
 * when the template holds no literal string there.
 */
function renderedName(resource: cdk.CfnResource, property: string): string | undefined {
	if (!isRenderable(resource)) return undefined;
	const rendered: unknown = cdk.Stack.of(resource).resolve(resource._toCloudFormation());
	const resources = field(rendered, 'Resources');
	if (typeof resources !== 'object' || resources === null) return undefined;
	// The rendering holds this resource only, under its logical id.
	for (const entry of Object.values(resources)) {
		const name = field(field(entry, 'Properties'), property);
		return typeof name === 'string' ? name : undefined;
	}
	return undefined;
}

/** The own property `key` of `value`, when `value` is an object. */
function field(value: unknown, key: string): unknown {
	return typeof value === 'object' && value !== null ? Object.getOwnPropertyDescriptor(value, key)?.value : undefined;
}

/** Per backend root: whether the name check is registered. */
const RESOURCE_NAME_CHECK = Symbol.for('blocks:ResourceNameCheck');

/** A `Scope` as this check reads it: structural, so a second copy of `@aws-cdk-blocks/core` in the tree is recognized too. */
interface ScopeLike extends IConstruct {
	readonly id: string;
	readonly bbName?: string;
}

function isScopeLike(construct: IConstruct): construct is ScopeLike {
	const candidate = construct as { id?: unknown; fullId?: unknown };
	return typeof candidate.id === 'string' && typeof candidate.fullId === 'string';
}

/** The scopes between `node` and `root` (both exclusive), nearest first: the ids a name under them is joined from. */
function scopesAbove(node: IConstruct, root: IConstruct): ScopeLike[] {
	const scopes: ScopeLike[] = [];
	for (let current = node.node.scope; current && current !== root; current = current.node.scope) {
		if (isScopeLike(current)) scopes.push(current);
	}
	return scopes;
}

/** The distinct characters of `name` that `rule` does not accept, in order of appearance. */
function rejectedCharacters(name: string, rule: NameRule): string[] {
	const checked = rule.suffix && name.endsWith(rule.suffix) ? name.slice(0, -rule.suffix.length) : name;
	return [...new Set(checked)].filter((character) => !rule.accepts.test(character));
}

/** `'a'`, `'a' and 'b'`, `'a', 'b' and 'c'`. */
function quotedList(items: readonly string[]): string {
	const quoted = items.map((item) => `'${item}'`);
	return quoted.length < 2 ? quoted.join('') : `${quoted.slice(0, -1).join(', ')} and ${quoted[quoted.length - 1]}`;
}

/** What one id breaks: its rejected characters, and the names that hold them, by rule. */
interface IdFinding {
	readonly characters: Set<string>;
	readonly names: Map<NameRule, string[]>;
}

/**
 * The errors for the resource names under `root` that their service will
 * reject: one per id that put a rejected character into a name, listing the
 * names, and one per resource whose name no id above it explains (an explicit
 * name option).
 */
function resourceNameErrors(root: Construct): string[] {
	const byScope = new Map<ScopeLike, IdFinding>();
	const errors: string[] = [];
	for (const node of root.node.findAll()) {
		if (!cdk.CfnResource.isCfnResource(node) || !Object.hasOwn(NAME_RULES, node.cfnResourceType)) continue;
		const rule = NAME_RULES[node.cfnResourceType];
		const scopes = scopesAbove(node, root);
		if (scopes.length === 0) continue;
		const name = renderedName(node, rule.property);
		if (name === undefined) continue;
		const rejected = rejectedCharacters(name, rule);
		if (rejected.length === 0) continue;
		// The ids that put a rejected character into this name. An id that was cut
		// off by the block's length limit, or a name that was passed explicitly,
		// matches none, and the resource is reported on its own.
		const sources = scopes.filter(
			(scope) => name.includes(scope.id) && rejected.some((character) => scope.id.includes(character)),
		);
		if (sources.length === 0) {
			errors.push(
				`The ${rule.what} name '${name}' of ${scopes[0].node.path} contains ${quotedList(rejected)}, but ` +
					`${rule.what} names may contain only ${rule.acceptsText}: the deploy would fail when the resource is created.`,
			);
			continue;
		}
		for (const scope of sources) {
			const finding = byScope.get(scope) ?? {
				characters: new Set<string>(),
				names: new Map<NameRule, string[]>(),
			};
			byScope.set(scope, finding);
			for (const character of rejected) if (scope.id.includes(character)) finding.characters.add(character);
			finding.names.set(rule, [...(finding.names.get(rule) ?? []), name]);
		}
	}
	for (const [scope, { characters, names }] of byScope) {
		const inIdOrder = [...new Set(scope.id)].filter((character) => characters.has(character));
		errors.push(
			[
				`${scope.bbName ?? 'Scope'} id '${scope.id}' (${scope.node.path}) contains ${quotedList(inIdOrder)}. ` +
					'An id is part of the name of each resource under it, so the deploy would fail when these are created:',
				...[...names].map(
					([rule, ruleNames]) =>
						`  - ${ruleNames.map((n) => `'${n}'`).join(', ')}: ` +
						`${rule.what} names may contain only ${rule.acceptsText}`,
				),
				'Rename the id: lowercase letters, digits and hyphens are accepted in every resource name. Renaming an ' +
					'id renames every resource under it, and so replaces any that is already deployed; if some are, keep ' +
					'the id and create the new Building Block under a scope with another id.',
			].join('\n'),
		);
	}
	return errors;
}

/**
 * Register, once per backend root, the validation that fails `cdk synth` when
 * a resource under a `Scope` has a physical name its service will reject.
 * Called by the CDK `Scope` constructor.
 *
 * @param scope - The scope being constructed.
 * @internal
 */
export function ensureResourceNameCheck(scope: Construct): void {
	getOrCreateOnRoot(scope, RESOURCE_NAME_CHECK, (root) => {
		root.node.addValidation({ validate: () => resourceNameErrors(root) });
		return true;
	});
}
