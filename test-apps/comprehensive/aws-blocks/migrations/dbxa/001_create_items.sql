-- Same table name as dbxb's: each block has its own schema on the shared cluster.
-- DSQL identity columns are BIGINT with an explicit CACHE (1, or at least 65536); UNIQUE is declared inline in CREATE TABLE.
CREATE TABLE IF NOT EXISTS items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY,
  sku TEXT UNIQUE NOT NULL,
  qty INTEGER NOT NULL DEFAULT 0
);
