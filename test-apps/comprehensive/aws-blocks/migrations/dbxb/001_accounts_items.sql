-- Foreign keys, a check constraint, an index and a view, written as DSQL documents them:
-- a constraint added with ALTER TABLE is NOT VALID and then validated by an asynchronous
-- job (ALTER TABLE ASYNC ... VALIDATE CONSTRAINT); an index is built ASYNC. The block waits
-- for each job before the next statement, so the constraints are enforced when the app starts.
CREATE TABLE IF NOT EXISTS accounts (
  id TEXT PRIMARY KEY,
  owner TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY,
  account_id TEXT NOT NULL,
  amount INTEGER NOT NULL
);
ALTER TABLE items ADD CONSTRAINT items_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE NOT VALID;
ALTER TABLE ASYNC items VALIDATE CONSTRAINT items_account;
ALTER TABLE items ADD CONSTRAINT items_amount_positive CHECK (amount >= 0) NOT VALID;
ALTER TABLE ASYNC items VALIDATE CONSTRAINT items_amount_positive;
CREATE INDEX ASYNC items_account_idx ON items (account_id);
CREATE VIEW account_totals AS
  SELECT account_id, SUM(amount) AS total FROM items GROUP BY account_id;
