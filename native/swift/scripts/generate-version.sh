# Generates committed Version.swift from package.json; SwiftPM consumers do not run this script.
#
# Usage:
#   generate-version.sh            writes Version.swift
#   generate-version.sh --check    verifies Version.swift is current
#
# Builds and tests do not detect version drift, so CI must run --check.

set -euo pipefail

CHECK=false
if [[ "${1:-}" == "--check" ]]; then
  CHECK=true
elif [[ -n "${1:-}" ]]; then
  echo "Usage: generate-version.sh [--check]" >&2
  exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# PROJECT_DIR defaults to the package root (parent of scripts/) but can be
# overridden (e.g. by tests) to point at a fixture directory.
PROJECT_DIR="${PROJECT_DIR:-$(cd "$SCRIPT_DIR/.." && pwd)}"

PKG_JSON="$PROJECT_DIR/package.json"
SWIFTFORMAT="$PROJECT_DIR/.swiftformat"
TARGET="$PROJECT_DIR/Sources/BlocksRuntime/Version.swift"

VERSION=$(node -p "require('$PKG_JSON').version")

# The version half of the token grammar: N.N.N, optional -prerelease, no build metadata.
if [[ ! "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?$ ]]; then
  echo "Version \"$VERSION\" in package.json is outside the N.N.N[-prerelease] token format (no build metadata)." >&2
  exit 1
fi

# Read the licence header from .swiftformat rather than duplicating it, so
# swiftformat and this generator cannot demand different headers. The option
# encodes line breaks as the two characters backslash and n.
if [[ ! -f "$SWIFTFORMAT" ]]; then
  echo "Cannot read $SWIFTFORMAT. The Swift licence header lives there." >&2
  exit 1
fi
HEADER_RAW=$(sed -nE 's/^--header "(.*)"[[:space:]]*$/\1/p' "$SWIFTFORMAT" | head -1)
if [[ -z "$HEADER_RAW" ]]; then
  echo "No quoted --header value in $SWIFTFORMAT to use as the Swift licence header." >&2
  exit 1
fi
HEADER="${HEADER_RAW//\\n/$'\n'}"

EXPECTED="$(cat <<EOF
$HEADER

// Auto-generated by native/swift/scripts/generate-version.sh. Do not edit manually.
// Source of truth: native/swift/package.json

let blocksRuntimeVersion = "$VERSION"

/// The user agent token for this runtime, e.g. \`aws-blocks-swift/$VERSION\`.
/// Keep the \`aws-blocks\` prefix: rows without it do not appear in reporting.
let blocksUserAgentToken = "aws-blocks-swift/\(blocksRuntimeVersion)"
EOF
)"

if [[ "$CHECK" == true ]]; then
  # Normalize CRLF so a Windows checkout (core.autocrlf) does not report false drift.
  if [[ -f "$TARGET" ]] && [[ "$(tr -d '\r' < "$TARGET")" == "$EXPECTED" ]]; then
    echo "ok: $TARGET matches package.json ($VERSION)"
    exit 0
  fi
  if [[ -f "$TARGET" ]]; then
    echo "DRIFT: $TARGET does not match package.json ($VERSION)." >&2
  else
    echo "DRIFT: $TARGET is missing." >&2
  fi
  echo "       Run: native/swift/scripts/generate-version.sh" >&2
  exit 1
fi

printf '%s\n' "$EXPECTED" > "$TARGET"
echo "Generated $TARGET ($VERSION)"
