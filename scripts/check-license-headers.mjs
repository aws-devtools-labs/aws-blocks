/**
 * Checks that every tracked source file under packages/, native/ and scripts/
 * carries the Apache-2.0 license header.
 *
 *   node scripts/check-license-headers.mjs         # report and exit 1 on misses
 *   node scripts/check-license-headers.mjs --fix   # insert the header where missing
 *
 * A file passes when one of its first HEADER_SCAN_LINES lines (counted after an
 * optional shebang or `// swift-tools-version` line) contains
 * `SPDX-License-Identifier: Apache-2.0` (or the older long-form Apache-2.0
 * notice, kept in native/kotlin/plugin/build.gradle.kts). Files are enumerated with
 * `git ls-files`, so untracked and gitignored build output is never scanned.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Top-level trees that are scanned. tasks/, test-apps/ and root config files are not published, so they are out of scope. */
const ROOTS = ['packages/', 'native/', 'scripts/'];

/** File extensions that must carry a header. */
const EXTENSIONS = new Set(['ts', 'tsx', 'mts', 'cts', 'js', 'mjs', 'cjs', 'kt', 'kts', 'dart', 'swift']);

/**
 * Paths that are deliberately left without a header. Each entry is a RegExp
 * tested against the repo-relative path, with the reason next to it.
 */
const EXCLUSIONS = [
	// Scaffolds copied into a user's new project; the user owns that code.
	[/^packages\/create-blocks-app\/templates\//, 'user project scaffolds'],
	// Codegen goldens and fixture outputs mirror the code generated into user
	// projects, which carries no header.
	[/^native\/codegen-fixtures\//, 'codegen golden outputs'],
	[/^native\/kotlin\/fixture-goldens\//, 'Kotlin codegen goldens'],
	// Written by Next.js on every build; a header would be overwritten.
	[/^packages\/admin-ui\/next-env\.d\.ts$/, 'generated by Next.js'],
	// Build output, dependencies and tool caches (normally untracked anyway).
	[/(^|\/)(node_modules|dist|build|\.dart_tool|\.build|\.next)\//, 'build output / dependencies'],
	// Gradle wrapper scripts carry Gradle's own license header.
	[/(^|\/)gradlew(\.bat)?$/, 'Gradle wrapper'],
];

/** How many lines (after a shebang / swift-tools-version line) are searched. */
const HEADER_SCAN_LINES = 6;
const SPDX_MARKER = 'SPDX-License-Identifier: Apache-2.0';
/** The older long-form notice also counts as a header. */
const ACCEPTED_MARKERS = [SPDX_MARKER, 'Licensed under the Apache License, Version 2.0'];

const SLASH_HEADER = [
	'// Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.',
	'// SPDX-License-Identifier: Apache-2.0',
];

/** Matches the header enforced by native/swift/.swiftformat. */
const SWIFT_HEADER = [
	'//',
	'// Copyright Amazon.com Inc. or its affiliates.',
	'// All Rights Reserved.',
	'//',
	'// SPDX-License-Identifier: Apache-2.0',
	'//',
];

function extensionOf(path) {
	const dot = path.lastIndexOf('.');
	return dot === -1 ? '' : path.slice(dot + 1);
}

function excludedBy(path) {
	return EXCLUSIONS.find(([pattern]) => pattern.test(path));
}

/** Number of leading lines that must stay above the header (0 or 1). */
function preambleLength(lines) {
	const first = lines[0] ?? '';
	if (first.startsWith('#!') || first.startsWith('// swift-tools-version')) return 1;
	return 0;
}

function hasHeader(text) {
	const lines = text.split('\n');
	const start = preambleLength(lines);
	return lines.slice(start, start + HEADER_SCAN_LINES).some((line) => ACCEPTED_MARKERS.some((marker) => line.includes(marker)));
}

function withHeader(text, path) {
	// Keep a leading byte-order mark at the very front, above the header.
	const bom = text.startsWith('\uFEFF') ? '\uFEFF' : '';
	if (bom) text = text.slice(1);
	const eol = text.includes('\r\n') ? '\r\n' : '\n';
	const lines = text.split(/\r?\n/);
	const start = preambleLength(lines);
	const header = extensionOf(path) === 'swift' ? SWIFT_HEADER : SLASH_HEADER;
	const before = lines.slice(0, start);
	let rest = lines.slice(start);
	// Collapse leading blank lines so exactly one separates header and code.
	while (rest.length > 1 && rest[0].trim() === '') rest = rest.slice(1);
	const body = rest.length === 1 && rest[0] === '' ? [''] : ['', ...rest];
	return bom + [...before, ...header, ...body].join(eol);
}

function trackedFiles() {
	const out = execFileSync('git', ['ls-files', '-z', '--', ...ROOTS], { cwd: repoRoot, encoding: 'utf8' });
	return out.split('\0').filter(Boolean);
}

function main() {
	const fix = process.argv.includes('--fix');
	const missing = [];
	for (const path of trackedFiles()) {
		if (!EXTENSIONS.has(extensionOf(path))) continue;
		if (excludedBy(path)) continue;
		const abs = join(repoRoot, path);
		let text;
		try {
			text = readFileSync(abs, 'utf8');
		} catch {
			// Deleted in the working tree but still in the index.
			continue;
		}
		if (hasHeader(text)) continue;
		if (fix) writeFileSync(abs, withHeader(text, path));
		missing.push(path);
	}

	if (missing.length === 0) {
		console.log('All tracked source files carry the Apache-2.0 license header.');
		return;
	}
	if (fix) {
		console.log(`Added the license header to ${missing.length} file(s):`);
		for (const path of missing) console.log(`  ${path}`);
		return;
	}
	console.error(`${missing.length} file(s) are missing the license header (${SPDX_MARKER}):`);
	for (const path of missing) console.error(`  ${path}`);
	console.error('\nRun `node scripts/check-license-headers.mjs --fix` to add it.');
	process.exitCode = 1;
}

main();
