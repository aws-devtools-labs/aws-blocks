#!/usr/bin/env node
/**
 * Generates the committed version constant for each native runtime library.
 *
 * Usage:
 *   node scripts/generate-native-versions.mjs --swift            writes the constant
 *   node scripts/generate-native-versions.mjs --swift --check    verifies it is current (CI)
 *
 * Why the constant is committed rather than generated at build time:
 * Swift and Dart consumers build our source directly via SwiftPM and pub, and
 * neither runs our scripts. A build-time generator would therefore never run on
 * a customer's machine, so the value has to be in the tree.
 *
 * That makes the --check mode load bearing. A stale constant fails no build and
 * passes every test, so nothing else catches it drifting from the package version.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

const SWIFTFORMAT_CONFIG = 'native/swift/.swiftformat';

// The version half of the token grammar: N.N.N, optional -prerelease, no build metadata.
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.]{1,20})?$/;

/**
 * Reads the Swift licence header from .swiftformat rather than duplicating it,
 * so swiftformat and the drift check cannot end up demanding different headers.
 */
function readSwiftHeader() {
	const configPath = join(repoRoot, SWIFTFORMAT_CONFIG);
	let raw;
	try {
		raw = readFileSync(configPath, 'utf-8');
	} catch {
		console.error(`Cannot read ${SWIFTFORMAT_CONFIG}. The Swift licence header lives there.`);
		process.exit(1);
	}
	// Assumes a single-line, quote-free --header value (true of our .swiftformat).
	const match = raw.match(/^--header\s+"([^"]*)"\s*$/m);
	if (!match) {
		console.error(`No quoted --header value in ${SWIFTFORMAT_CONFIG} to use as the Swift licence header.`);
		process.exit(1);
	}
	// The option encodes line breaks as the two characters \ and n.
	return `${match[1].replaceAll('\\n', '\n')}\n`;
}

/**
 * One entry per native runtime. `versionSource` is the single source of truth
 * (the changesets-managed package.json, or a pubspec), `target` is the file we
 * generate, and `render` turns a semver into that file's full contents.
 */
const TARGETS = {
	swift: {
		versionSource: 'native/swift/package.json',
		readVersion: (raw) => {
			const v = JSON.parse(raw).version;
			return typeof v === 'string' ? v : undefined;
		},
		target: 'native/swift/Sources/BlocksRuntime/Version.swift',
		render: (version) => `${readSwiftHeader()}
// Auto-generated by scripts/generate-native-versions.mjs. Do not edit manually.
// Source of truth: native/swift/package.json

/// Semver of this AWS Blocks Swift runtime library.
public let blocksRuntimeVersion = "${version}"

/// The user agent token for this runtime, e.g. \`aws-blocks-swift/${version}\`.
/// Keep the \`aws-blocks\` prefix: rows without it do not appear in reporting.
public let blocksUserAgentToken = "aws-blocks-swift/\\(blocksRuntimeVersion)"
`,
	},
	dart: {
		versionSource: 'native/dart/packages/blocks_runtime/pubspec.yaml',
		// pubspec.yaml is YAML; with no YAML parser available, extract the
		// top-level `version:` field. The `^`/`m` anchor prevents matching an
		// indented `version:` under a dependency.
		readVersion: (raw) => raw.match(/^version:\s*(\S+)\s*$/m)?.[1],
		target: 'native/dart/packages/blocks_runtime/lib/src/version.dart',
		// Top-level constants rather than a class holding statics: the package's
		// analysis_options.yaml enables `avoid_classes_with_only_static_members`.
		render: (version) => `// Auto-generated by scripts/generate-native-versions.mjs. Do not edit manually.
// Source of truth: native/dart/packages/blocks_runtime/pubspec.yaml

/// Semver of this AWS Blocks Dart runtime library.
const String blocksRuntimeVersion = '${version}';

/// The user agent token for this runtime, e.g. \`aws-blocks-dart/${version}\`.
/// Keep the \`aws-blocks\` prefix: rows without it do not appear in reporting.
const String blocksUserAgentToken = 'aws-blocks-dart/$blocksRuntimeVersion';
`,
	},
};

const args = process.argv.slice(2);
const check = args.includes('--check');
const names = args.filter((a) => !a.startsWith('--'));
const targetFlags = Object.keys(TARGETS).map((name) => `--${name}`);
const usage = `Usage: node scripts/generate-native-versions.mjs <${targetFlags.join('|')}> [--check]`;

// Fail fast on a mistyped flag (e.g. --chekc) rather than silently ignoring it,
// which could otherwise run in write mode when --check was intended.
const unknownFlags = args.filter((a) => a.startsWith('--') && a !== '--check' && !targetFlags.includes(a));
if (unknownFlags.length > 0) {
	console.error(`Unknown flag(s): ${unknownFlags.join(', ')}`);
	console.error(usage);
	process.exit(1);
}

const selected = [
	...new Set(Object.keys(TARGETS).filter((name) => args.includes(`--${name}`)).concat(names)),
];

if (selected.length === 0) {
	console.error(usage);
	console.error(`Known targets: ${Object.keys(TARGETS).join(', ')}`);
	process.exit(1);
}

let drifted = false;

for (const name of selected) {
	const spec = TARGETS[name];
	if (!spec) {
		console.error(`Unknown target "${name}". Known: ${Object.keys(TARGETS).join(', ')}`);
		process.exit(1);
	}

	let rawVersion;
	try {
		rawVersion = readFileSync(join(repoRoot, spec.versionSource), 'utf-8');
	} catch {
		console.error(`Cannot read ${spec.versionSource}.`);
		process.exit(1);
	}
	const version = spec.readVersion(rawVersion);
	if (!version) {
		console.error(`No version found in ${spec.versionSource}`);
		process.exit(1);
	}
	if (!SEMVER.test(version)) {
		console.error(`Version "${version}" in ${spec.versionSource} is not a valid token semver (N.N.N, optional -prerelease, no build metadata).`);
		process.exit(1);
	}

	const expected = spec.render(version);
	const targetPath = join(repoRoot, spec.target);

	if (check) {
		let actual = null;
		try {
			actual = readFileSync(targetPath, 'utf-8');
		} catch {
			actual = null;
		}
		// Normalize CRLF so a Windows checkout (core.autocrlf) does not report false drift.
		if (actual !== null && actual.replaceAll('\r\n', '\n') === expected) {
			console.log(`ok   ${name}: ${spec.target} matches ${spec.versionSource} (${version})`);
			continue;
		}
		drifted = true;
		console.error(
			actual === null
				? `DRIFT ${name}: ${spec.target} is missing.`
				: `DRIFT ${name}: ${spec.target} does not match ${spec.versionSource} (${version}).`,
		);
		console.error(`      Run: node ${relative(repoRoot, fileURLToPath(import.meta.url))} --${name}`);
		continue;
	}

	writeFileSync(targetPath, expected);
	console.log(`Generated ${spec.target}: ${version}`);
}

if (drifted) {
	console.error('\nVersion constants are out of date. A stale constant fails no build and passes');
	console.error('every test, so nothing else catches it drifting. Regenerate and commit.');
	process.exit(1);
}
